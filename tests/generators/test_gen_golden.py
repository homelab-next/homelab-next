def test_write_tree_refuses_nothing_outside_root(tmp_path):
    from homelabnext.generators.core import flatten as fl

    with pytest.raises(RuntimeError, match="unsafe"):
        fl({"x": {"../escape": "a\n"}})
    with pytest.raises(RuntimeError, match="trailing newline"):
        fl({"x": {"ok": "no newline"}})
    with pytest.raises(RuntimeError, match="both write"):
        fl({"x": {"p": "a\n"}, "y": {"p": "b\n"}})
