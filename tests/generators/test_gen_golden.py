def test_no_output_leaks_a_registry_address_into_endpoints():
    """Endpoints in consumer configs use aliases; addresses appear only in DNS/hosts/zone data."""
    addrs = {h.address for h in REG.hosts.values()}
    allowed = {
        "dns/svc.example.internal.zone",
        "dns/example.internal.hosts.zone",
        "hosts/hosts.block",
        "docs/services.md",
    }
    for rel, text in flatten(generate(REG)).items():
        if rel in allowed:
            continue
        for a in addrs:
            assert a not in text, f"{rel} contains raw address {a}"


