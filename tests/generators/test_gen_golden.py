def test_hosts_block_apply_is_idempotent_and_preserves_other_lines():
    block = generate(REG, ["hosts_file"])["hosts_file"]["hosts/hosts.block"]
    base = "ff02::1 ip6-allnodes\n"
    once = apply_hosts_block(base, block)
    twice = apply_hosts_block(once, block)
    assert (
        once == twice
        and once.startswith(base)
        and once.count(HOSTS_BEGIN) == 1
        and once.count(HOSTS_END) == 1
    )
    from homelabnext.registry import parse_hosts

    parsed = parse_hosts(once)
    assert REG.hosts["lake-core"].address in parsed["lake-query.svc.example.internal"]
    assert "ip6-allnodes" in parsed


