@pytest.mark.parametrize("gen", sorted(generate(REG)))
def test_each_generator_matches_golden(gen):
    out = generate(REG, [gen])[gen]
    assert out, f"{gen} produced nothing"
    for rel, text in out.items():
        golden = GOLDEN / rel
        assert golden.is_file(), f"missing golden {rel}"
        assert golden.read_text(encoding="utf-8") == text, f"{rel} differs from golden"


def test_golden_tree_has_no_extra_files():
    files = flatten(generate(REG))
    on_disk = {p.relative_to(GOLDEN).as_posix() for p in GOLDEN.rglob("*") if p.is_file()}
    assert on_disk == set(files)


def test_generation_is_deterministic_across_runs():
    assert flatten(generate(REG)) == flatten(generate(load(EXAMPLE)))


def test_idempotent_rerun_does_not_touch_files(tmp_path):
    files = flatten(generate(REG))
    first = write_tree(tmp_path, files)
    assert len(first.written) == len(files) and not first.unchanged
    stamps = {p: (tmp_path / p).stat().st_mtime_ns for p in files}
    second = write_tree(tmp_path, files)
    assert second.written == [] and second.pruned == [] and len(second.unchanged) == len(files)
    assert stamps == {p: (tmp_path / p).stat().st_mtime_ns for p in files}
    assert check_tree(tmp_path, files) == []


def test_removed_service_prunes_only_generated_files(tmp_path):
    files = flatten(generate(REG))
    write_tree(tmp_path, files)
    (tmp_path / "env" / "hand-written.env.generated").write_text(
        "MINE=1\n"
    )  # no marker: must survive
    import yaml as y

    doc = y.safe_load(EXAMPLE.read_text())
    del doc["services"]["agent-runtime"]
    smaller = flatten(generate(build_registry(doc)))
    assert check_tree(tmp_path, smaller)  # drift detected, including stale
    res = write_tree(tmp_path, smaller)
    assert "env/agent-runtime.env.generated" in res.pruned
    assert (tmp_path / "env" / "hand-written.env.generated").exists()
    assert (
        "agent-runtime"
        not in (tmp_path / "docs" / "services.md")
        .read_text()
        .split("## Service cards")[0]
        .split("## Capabilities")[1]
    )


def test_registry_change_changes_dependent_outputs_only():
    doc = yaml.safe_load(EXAMPLE.read_text())
    doc["services"]["notify"]["port"] = 8097
    new = flatten(generate(build_registry(doc)))
    old = flatten(generate(REG))
    changed = {p for p in new if new[p] != old.get(p)}
    # header digest changes everywhere, so compare bodies without the header line
    body = lambda t: "\n".join(ln for ln in t.splitlines() if "sha256:" not in ln)  # noqa: E731
    really = {p for p in new if body(new[p]) != body(old[p])}
    assert "env/agent-runtime.env.generated" in really
    assert "systemd/agent-runtime.service.d/10-hnx-endpoints.conf" in really
    assert "env/lake-query.env.generated" not in really
    assert "caddy/sites.caddy" not in really
    assert changed  # digests differ


