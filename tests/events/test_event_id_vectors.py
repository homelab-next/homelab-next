"""The shared event id vectors are what ``derive_event_id`` says.

The orchestrator's Go ``events.DeriveID`` re-implements the derivation (``json.dumps`` with
``ensure_ascii=True`` and compact separators, byte for byte), and its test reads
``conformance/fixtures/event_id_vectors.json`` in place.  The file is generated here from
:func:`homelabnext.events.envelope.derive_event_id` itself and must match it byte for byte, so a
change to the Python derivation that is not carried to Go fails one side or the other.  To
regenerate after a deliberate change: ``HNX_REGEN_EVENT_ID_VECTORS=1 pytest`` on this file.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

from homelabnext.events.envelope import derive_event_id

VECTORS = Path(__file__).resolve().parents[2] / "conformance/fixtures/event_id_vectors.json"

#: (name, event type, source, subject, dedupe key); subject None is "no subject", which the
#: derivation hashes as ""
INPUTS: list[tuple[str, str, str, str | None, str]] = [
    ("job-started", "homelabnext.agent.job.started", "svc:orchestrator", "0123abcd",
     "0123abcd:homelabnext.agent.job.started"),
    ("empty-subject", "homelabnext.task.queued", "svc:siem", "", "job-17"),
    ("no-subject", "homelabnext.task.queued", "svc:siem", None, "job-17"),
    ("html-characters", "t.x", "svc:a", "s", "k<&>"),
    ("quote-and-backslash", "t.x", "svc:a", 'say "hi"', "back\\slash/"),
    ("latin-1", "t.x", "svc:a", "caf\u00e9", "na\u00efve"),
    ("bmp-cjk", "t.x", "svc:a", "\u4e8b\u4ef6", "\u30ad\u30fc"),
    ("line-separators", "t.x", "svc:a", "a\u2028b", "c\u2029d"),
    ("astral", "t.x", "svc:a", "\U0001f600", "\U0001d11e\U00010000\U0010ffff"),
    ("mixed", "t.x", "svc:a", "caf\u00e9", "k\u2028\U0001f600\n\x01"),
    ("c0-controls", "t.x", "svc:a", "\x00\x08\x09\x0a\x0c\x0d", "\x1b\x1f"),
    ("del", "t.x", "svc:a", "s\x7f", "k\x7fz"),
    ("c1-controls", "t.x", "svc:a", "\x80\x9f", "\xa0\xff"),
    ("bom-and-replacement", "t.x", "svc:a", "\ufeff", "\ufffd\uffff"),
    ("long-key", "t.x", "svc:a", "s", "k" * 4096),
]  # fmt: skip


def build() -> dict:
    vectors = [
        {
            "name": name,
            "type": typ,
            "source": src,
            "subject": subj,
            "dedupe_key": key,
            "id": derive_event_id(typ, src, key, subject=subj),
        }
        for name, typ, src, subj, key in INPUTS
    ]
    return {
        "description": (
            "Test vectors for the derived event id, generated by "
            "tests/events/test_event_id_vectors.py from "
            "homelabnext.events.envelope.derive_event_id: 'evt-' and the first 32 hex characters "
            "of the SHA-256 of the JSON array [type, source, subject, dedupe_key], written with "
            "compact separators and ensure_ascii (DEL and every non-ASCII character escaped, a "
            "surrogate pair above the BMP). subject null = no subject, hashed as the empty "
            "string. Lone surrogates are not vectors: a Go string cannot hold one, so the two "
            "languages cannot be given the same input."
        ),
        "vectors": vectors,
    }


def _text() -> str:
    # ensure_ascii keeps every control and astral character escaped in the file itself
    return json.dumps(build(), indent=1, ensure_ascii=True) + "\n"


def test_the_vectors_file_is_what_derive_event_id_says():
    if os.environ.get("HNX_REGEN_EVENT_ID_VECTORS") == "1":
        VECTORS.write_text(_text(), encoding="utf-8")
    assert VECTORS.read_text(encoding="utf-8") == _text(), (
        "conformance/fixtures/event_id_vectors.json is stale: rerun this test with "
        "HNX_REGEN_EVENT_ID_VECTORS=1 after a deliberate change to derive_event_id"
    )


def test_the_vectors_file_round_trips_its_inputs():
    """What the file holds decodes back to exactly the inputs, so a reader in another language
    hashes the same strings this side did."""
    vs = json.loads(VECTORS.read_text(encoding="utf-8"))["vectors"]
    assert [
        (v["name"], v["type"], v["source"], v["subject"], v["dedupe_key"]) for v in vs
    ] == INPUTS
    assert len({v["id"] for v in vs if v["name"] != "no-subject"}) == len(vs) - 1


def test_the_vectors_cover_every_escape_class():
    text = "".join((s or "") + k for _, _, _, s, k in INPUTS)
    assert "\x7f" in text and "\x00" in text, "DEL and NUL"
    assert any(0x80 <= ord(c) <= 0x9F for c in text), "C1 controls"
    assert any(0xA0 <= ord(c) <= 0xFFFF for c in text), "BMP"
    assert any(ord(c) > 0xFFFF for c in text), "above the BMP"
    assert {"\u2028", "\u2029", "<", "&", ">", '"', "\\"} <= set(text)


def test_no_subject_and_empty_subject_derive_the_same_id():
    by = {v["name"]: v["id"] for v in build()["vectors"]}
    assert by["no-subject"] == by["empty-subject"]
