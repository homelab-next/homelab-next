def test_goldens():
    out = render(fleet_from(DATA / "_nodes.yml"), TARGET)
    if os.environ.get("HNX_UPDATE_GOLDEN") == "1":
        shutil.rmtree(GOLDEN, ignore_errors=True)
        for rel, text in out.items():
            (GOLDEN / rel).parent.mkdir(parents=True, exist_ok=True)
            (GOLDEN / rel).write_text(text, encoding="utf-8")
    want = {
        p.relative_to(GOLDEN).as_posix(): p.read_text() for p in GOLDEN.rglob("*") if p.is_file()
    }
    assert set(out) == set(want)
    for rel in out:
        assert out[rel] == want[rel], f"{rel} differs from golden"
    assert "nodes/hv-d/host.fw" not in out  # no host_firewall, no file


def rules_of(text: str) -> list[str]:
    return text.split("[RULES]\n", 1)[1].splitlines()


def test_a_standalone_node_gets_its_allows_and_nothing_else():
    out = render(fleet_from(DATA / "_nodes.yml"), TARGET)["nodes/hv-a/host.fw"]
    assert out.startswith("# generated by hnx guests render; do not edit\n")
    assert "[OPTIONS]\nenable: 1\n" in out
    assert "policy_in" not in out and "policy_out" not in out  # a node file has no policy option
    # a zone with an IPv6 prefix is one line per address family
    assert [r.split(" # ")[1] for r in rules_of(out)] == [
        *["pve-ssh"] * 3,
        *["pve-web"] * 2,
        *["pve-icmp"] * 2,
        *["pve-console"] * 2,
        "pve-spice",
    ]
    assert "IN ACCEPT -p tcp -dport 22 -source 192.0.2.0/24 -log nolog # pve-ssh" in out
    assert "IN ACCEPT -p tcp -dport 22 -source 198.51.100.7/32 -log nolog # pve-ssh" in out
    assert "-dport 5900:5999 -source 192.0.2.0/24" in out
    assert "-dport 3128 -source 198.51.100.7/32" in out
    assert "5405" not in out  # not in a cluster, no corosync


