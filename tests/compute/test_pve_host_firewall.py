# ------------------------------------------------------------------------------ the scripts
def scripts(tmp_path: Path, nodes: dict | None = None) -> Path:
    out = render(fleet_with(tmp_path, nodes or hf()), TARGET)
    d = tmp_path / "rendered"
    d.mkdir()
    for rel, text in out.items():
        if rel.startswith("nodes/hv-a/"):
            (d / Path(rel).name).write_text(text, encoding="utf-8")
    return d


@pytest.mark.requires_tool("shellcheck")
def test_the_scripts_pass_shellcheck(tmp_path):
    d = scripts(tmp_path)
    for name in ("hnx-host-firewall.sh", "hnx-host-firewall-run.sh"):
        subprocess.run(["shellcheck", "-s", "sh", str(d / name)], check=True)


def stub(path: Path, body: str) -> None:
    path.write_text("#!/bin/sh\n" + body, encoding="utf-8")
    path.chmod(path.stat().st_mode | stat.S_IXUSR)


class Node:
    """A fake node: PATH stubs for ``pve-firewall``, ``systemctl`` and ``systemd-run`` over a
    directory standing in for ``/etc/pve``.  Every call is logged to ``log``."""

    def __init__(self, tmp_path: Path, *, prior: str | None = "OLD RULES\n", dc: str | None = None):
        self.root = tmp_path / "node"
        self.bin = self.root / "bin"
        self.flags = self.root / "flags"  # a file here makes the named thing fail or be down
        self.node_dir = self.root / "pve" / "nodes" / "hv-a"
        self.state = self.root / "state"
        self.log = self.root / "log"
        for d in (self.bin, self.flags, self.node_dir):
            d.mkdir(parents=True)
        self.log.write_text("")
        self.cluster_fw = self.root / "pve" / "cluster.fw"
        self.cluster_fw.write_text("[OPTIONS]\nenable: 1\n" if dc is None else dc)
        self.host_fw = self.node_dir / "host.fw"
        if prior is not None:
            self.host_fw.write_text(prior)
        self.scripts = scripts(tmp_path)
        self.script = self.scripts / "hnx-host-firewall.sh"
        self.rendered = (self.scripts / "host.fw").read_text()
        stub(
            self.bin / "pve-firewall",
            'echo "pve-firewall $*" >> "$LOG"\n'
            '[ ! -e "$FLAGS/pve-firewall-$1-fails" ] || exit 1\n'
            'if [ "$1" = restart ]; then cp "$NODE_DIR/host.fw" "$LOG.live" 2>/dev/null '
            '|| echo none > "$LOG.live"; fi\n',
        )
        stub(
            self.bin / "systemctl",
            'echo "systemctl $*" >> "$LOG"\n'
            'case "$1" in\n'
            '  is-active) u=$3; case "$u" in *.timer) [ -e "$FLAGS/timer" ] ;;'
            '    *) [ ! -e "$FLAGS/down-$u" ] ;; esac ;;\n'
            '  stop) [ ! -e "$FLAGS/stop-fails" ] || exit 1; rm -f "$FLAGS/timer" ;;\n'
            "esac\n",
        )
        stub(
            self.bin / "systemd-run",
            'echo "systemd-run $*" >> "$LOG"\n'
            '[ ! -e "$FLAGS/arm-fails" ] || exit 1\n'
            'cmd=""; for a in "$@"; do case "$a" in --*) ;; *) cmd="$cmd $a" ;; esac; done\n'
            'echo "$cmd" > "$FLAGS/armed-cmd"; : > "$FLAGS/timer"\n',
        )
        self.env = {
            **os.environ,
            "PATH": f"{self.bin}:{os.environ['PATH']}",
            "LOG": str(self.log),
            "FLAGS": str(self.flags),
            "NODE_DIR": str(self.node_dir),
            "HNX_PVE_NODE_DIR": str(self.node_dir),
            "HNX_PVE_CLUSTER_FW": str(self.cluster_fw),
            "HNX_STATE_DIR": str(self.state),
        }

    def run(self, *args: str, **env: str) -> subprocess.CompletedProcess:
        return subprocess.run(
            ["sh", str(self.script), *args],
            env={**self.env, **env},
            capture_output=True,
            text=True,
            timeout=60,
            check=False,
        )

    def flag(self, name: str) -> None:
        (self.flags / name).write_text("")

    @property
    def armed(self) -> bool:
        return (self.flags / "timer").exists()

    def fire_timer(self, **env: str) -> subprocess.CompletedProcess:
        """What systemd does when the timer elapses: run the armed command."""
        cmd = (self.flags / "armed-cmd").read_text().split()
        (self.flags / "timer").unlink(missing_ok=True)
        return subprocess.run(
            cmd, env={**self.env, **env}, capture_output=True, text=True, timeout=60, check=False
        )

    def calls(self) -> list[str]:
        return self.log.read_text().splitlines()


def test_apply_arms_the_timer_before_it_changes_anything(tmp_path):
    n = Node(tmp_path)
    r = n.run()
    assert r.returncode == 0, r.stderr
    calls = n.calls()
    arm = next(i for i, c in enumerate(calls) if c.startswith("systemd-run"))
    restart = calls.index("pve-firewall restart")
    assert arm < restart
    assert "--unit=hnx-hostfw-rollback-hv-a" in calls[arm] and "--on-active=5m" in calls[arm]
    assert n.host_fw.read_text() == n.rendered
    assert (n.state / "host.fw.prev").read_text() == "OLD RULES\n"
    assert "UNCONFIRMED" in r.stdout and n.armed


def test_apply_checks_the_ruleset_compiles_and_the_node_stays_healthy(tmp_path):
    n = Node(tmp_path)
    assert n.run().returncode == 0
    calls = n.calls()
    assert calls.index("pve-firewall compile") < calls.index("pve-firewall restart")
    for unit in ("pveproxy", "pvedaemon", "pve-firewall"):
        assert f"systemctl is-active --quiet {unit}" in calls


