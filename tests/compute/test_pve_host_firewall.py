def test_an_unconfirmed_apply_is_undone_when_the_timer_fires(tmp_path):
    n = Node(tmp_path)
    assert n.run().returncode == 0
    r = n.fire_timer()
    assert r.returncode == 0, r.stderr
    assert n.host_fw.read_text() == "OLD RULES\n"
    assert n.calls().count("pve-firewall restart") == 2  # on, and back off
    assert not (n.state / "pending").exists()
    assert n.run("confirm").returncode == 1  # a late confirm does not report a rolled-back file


def test_a_late_timer_does_not_undo_a_confirmed_file(tmp_path):
    n = Node(tmp_path)
    assert n.run().returncode == 0
    cmd = (n.flags / "armed-cmd").read_text()
    assert n.run("confirm").returncode == 0
    (n.flags / "armed-cmd").write_text(cmd)
    r = n.fire_timer()
    assert r.returncode == 0 and "nothing to roll back" in r.stdout
    assert n.host_fw.read_text() == n.rendered


