class Controller:
    """``ssh``, ``scp`` and the port check are stubs; ``rc.<verb>`` files make the node's
    apply/confirm/rollback fail and ``closed.<port>`` files make a port stop answering."""

    def __init__(self, tmp_path: Path):
        self.root = tmp_path / "ctl"
        self.bin = self.root / "bin"
        self.bin.mkdir(parents=True)
        self.log = self.root / "log"
        self.log.write_text("")
        self.scripts = scripts(tmp_path)
        self.script = self.scripts / "hnx-host-firewall-run.sh"
        stub(
            self.bin / "ssh",
            'echo "ssh $*" >> "$LOG"\n'
            "for last; do :; done\n"
            'case "$*" in\n'
            "  *mktemp*) echo /var/tmp/hnx-hostfw.abc123; exit 0 ;;\n"
            '  *"rm -rf"*) exit 0 ;;\n'
            "esac\n"
            '[ ! -e "$RC/rc.$last" ] || exit 1\n',
        )
        stub(self.bin / "scp", 'echo "scp $*" >> "$LOG"\n')
        stub(
            self.bin / "portcheck",
            'echo "portcheck $*" >> "$LOG"\n[ ! -e "$RC/closed.$2" ]\n',
        )
        stub(
            self.bin / "verify-hook", 'echo "verify-hook $*" >> "$LOG"\n[ ! -e "$RC/hook-fails" ]\n'
        )
        stub(self.bin / "sleep", "")
        self.env = {
            **os.environ,
            "PATH": f"{self.bin}:{os.environ['PATH']}",
            "LOG": str(self.log),
            "RC": str(self.root),
            "HNX_PORT_CHECK": str(self.bin / "portcheck"),
            "HNX_CHECK_TRIES": "3",
        }

    def run(self, *args: str, **env: str) -> subprocess.CompletedProcess:
        return subprocess.run(
            ["sh", str(self.script), *(args or ("ops@node.example.internal",))],
            env={**self.env, **env},
            capture_output=True,
            text=True,
            timeout=60,
            check=False,
        )

    def flag(self, name: str) -> None:
        (self.root / name).write_text("")

    def calls(self) -> list[str]:
        return self.log.read_text().splitlines()

    def verbs(self) -> list[str]:
        return [c.split()[-1] for c in self.calls() if re.search(r"hnx-host-firewall\.sh \w+$", c)]


def test_the_ports_answering_confirms(tmp_path):
    c = Controller(tmp_path)
    r = c.run()
    assert r.returncode == 0, r.stderr
    assert c.verbs() == ["apply", "confirm"]
    ports = [x for x in c.calls() if x.startswith("portcheck")]
