def nodes_file(tmp_path: Path, nodes: dict) -> Path:
    p = tmp_path / "_nodes.yml"
    p.write_text(yaml.safe_dump({"nodes": nodes}), encoding="utf-8")
    return p


def fleet_from(path: Path):
    return load_fleet(FLEET, STUB, nodes_path=path)


def fleet_with(tmp_path: Path, nodes: dict):
    return fleet_from(nodes_file(tmp_path, nodes))


def hf(**kw):
    return {"hv-a": {"host_firewall": {"management": copy.deepcopy(MGMT), **kw}}}


