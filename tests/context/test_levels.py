DOC = """---
title: Example
summary: One reviewed line about the example.
---
<!-- SPDX-License-Identifier: Apache-2.0 -->
# Example page

The first paragraph
spans two lines.

## Decision

Text.

```yaml
# not a heading: inside a fence
## nor this
```

### Consequences

More.

## Alternatives

~~~
## still code
~~~
"""


def _paths(text: str) -> list[str]:
    return [h.path for h in headings(text)]


def _slugs(text: str) -> list[str]:
    return [h.slug for h in headings(text)]


# -- front-matter -----------------------------------------------------------------------------


def test_front_matter_is_parsed_and_skipped():
    front, body = front_matter(DOC)
    assert front == {"title": "Example", "summary": "One reviewed line about the example."}
    assert DOC[body:].startswith("<!-- SPDX")
    assert front_matter("no block\n") == (None, 0)
    broken = "---\nkey: [unclosed\n---\n# Title\n"
    front, body = front_matter(broken)
    assert front is None and broken[body:] == "# Title\n"  # not YAML: still not body text
    assert front_matter("---\n---\nbody\n") == (None, 8)  # empty block: no mapping
    assert front_matter("---\n- a list\n---\n")[0] is None


def test_a_byte_order_mark_before_the_front_matter_is_skipped():
    text = "\ufeff" + DOC
    front, body = front_matter(text)
    assert front["summary"] == "One reviewed line about the example."
    assert body == 1 + front_matter(DOC)[1]
    assert summary_of(text, "a.md")[1] == "authored"
    assert headings(text)[0].title == "Example page"
    assert front_matter("\ufeffno block") == (None, 1)


@pytest.mark.parametrize(
    "block",
    [
        "a: [[[[[[x]]]]]",  # unbalanced flow collection
        "a: " + "x" * (levels.MAX_FRONT_CHARS + 1),  # too long to parse
        "a: !!python/object:os.system x",  # an unsafe tag: a constructor error
        "a: 1\na: 2",  # a duplicate key
    ],
)
def test_front_matter_that_fails_to_parse_in_any_way_is_none(block):
    text = f"---\n{block}\n---\n# T\n\nProse.\n"
    front, body = front_matter(text)
    assert front is None and text[body:] == "# T\n\nProse.\n"
    assert summary_of(text, "a.md") == ("Prose.", "first-paragraph")


def test_a_recursion_error_inside_the_yaml_parser_is_no_front_matter(monkeypatch):
    """Deep nesting (``[`` x 1000) makes PyYAML raise RecursionError, not a YAMLError; the parser
    is stubbed to raise it at once, since the real depth costs seconds."""
    import yaml

    def deep(*_a, **_k):
        raise RecursionError("maximum recursion depth exceeded")

    monkeypatch.setattr(yaml, "load", deep)
    levels.clear_memo()
    text = "---\na: [[[\n---\n# T\n\nProse.\n"
    assert front_matter(text) == (None, len("---\na: [[[\n---\n"))
    assert summary_of(text, "a.md") == ("Prose.", "first-paragraph")


# -- summaries --------------------------------------------------------------------------------


def test_authored_summary_wins():
    assert summary_of(DOC, "docs/example.md") == (
        "One reviewed line about the example.",
        "authored",
    )


def test_first_paragraph_fallback_skips_front_matter_comments_headings_and_code():
    plain = DOC.replace("summary: One reviewed line about the example.\n", "")
    assert summary_of(plain, "docs/example.md") == (
        "The first paragraph spans two lines.",
        "first-paragraph",
    )
    fenced_first = "# T\n\n```\ncode first\n```\n\nThen prose.\n"
    assert first_paragraph(fenced_first) == "Then prose."


def test_first_paragraph_skips_quotes_lists_tables_html_and_images():
    text = (
        "# T\n\n> Generated by a tool. Do not edit.\n\n- **Status:** proposed\n\n* item\n\n"
        "| a | b |\n\n<div>x</div>\n\n![img](a.png)\n\nThe prose.\n"
    )
    assert first_paragraph(text) == "The prose."


def test_without_prose_before_the_first_h2_an_adr_prefers_its_context():
    adr = (
        "# ADR-0099: Something\n\n- **Status:** proposed\n\n## Decision\n\nDecided.\n\n"
        "## Context\n\nWhy we decided.\n"
    )
    assert first_paragraph(adr) == "Why we decided."
    lesson = "## Symptom\n\nThe page broke.\n\n## Root cause\n\nNo check.\n"
    assert first_paragraph(lesson) == "The page broke."  # no Context: the first prose
    under_context = "# T\n\n## Context\n\n### Detail\n\nNested prose.\n"
    assert first_paragraph(under_context) == "Nested prose."
    early = "# T\n\nEarly prose.\n\n## Context\n\nLater.\n"
    assert first_paragraph(early) == "Early prose."  # prose before the first H2 wins


def test_first_paragraph_is_reduced_to_visible_text():
    text = "# T\n\nSee [the guide](g.md), [[agent|profiles]], [[graph]], `code`, *em*, <b>x</b>.\n"
    assert first_paragraph(text) == "See the guide, profiles, graph, code, em, x."


def test_a_long_first_paragraph_is_cut_at_a_sentence_or_a_word():
    sentences = "This first sentence is long enough to stand alone as the summary line. " * 3
    assert (
        first_paragraph("# T\n\n" + sentences + "\n")
        == ("This first sentence is long enough to stand alone as the summary line. " * 2).strip()
    )
    short = "Too short. " + "then a long run of words without an end " * 5
    assert first_paragraph("# T\n\n" + short + "\n").endswith("…")  # a sentence end too early
    words = first_paragraph("# T\n\n" + " ".join(["word"] * 100) + "\n")
    assert len(words) <= MAX_SUMMARY_CHARS and words.endswith("word…")
    one = first_paragraph("# T\n\n" + "x" * 400 + "\n")  # no space to cut at
    assert one == "x" * (MAX_SUMMARY_CHARS - 1) + "…"
    assert cut("fits.") == "fits." and cut("a. " + "b" * 300) == "a.…"  # the only word break


def test_no_paragraph_and_non_markdown_give_none():
    assert summary_of("# Only a heading\n", "a.md") == ("", "none")
    assert summary_of("", "a.md") == ("", "none")
    assert summary_of("summary: looks like one\n\nprose\n", "script.py") == ("", "none")
    assert is_markdown("docs/A.MD") and not is_markdown("tools/x.py")


def test_a_synthesized_node_summarises_its_first_line_and_plain_attributes():
    cap = (
        "scoped retrieval for agents: relation before keywords, no inactive or stale hits\n"
        'id: cap:context\nkind: cap\nclasses: ["read"]\n'
    )
    assert summary_of(cap, "", "cap:context") == (
        "scoped retrieval for agents: relation before keywords, no inactive or stale hits",
        "synthesized",
    )
    svc = 'dns\nid: svc:dns\nkind: svc\npath: examples/services.yml\nowner: "platform-team"\n'
    svc += 'tags: ["core", "edge"]\ndeclared_in: ["x"]\n'
    assert summary_of(svc, "examples/services.yml", "svc:dns") == (
        "dns: owner platform-team; tags core, edge",
        "synthesized",
    )
    # a real file's text is not synthesized, whatever its id
    assert summary_of("# x\n\nProse.\n", "docs/x.md", "doc:docs/x.md")[1] == "first-paragraph"


def test_a_malformed_authored_summary_is_not_served_as_authored():
    text = "---\nsummary: " + "y" * 200 + "\n---\nProse.\n"
    assert summary_of(text, "a.md") == ("Prose.", "first-paragraph")


# -- headings ---------------------------------------------------------------------------------


def test_headings_inside_fenced_code_are_ignored():
    # the sole leading H1 is the document's title, not a path segment
    assert _paths(DOC) == ["Example page", "Decision", "Decision/Consequences", "Alternatives"]
    unclosed = "# A\n\n```\n# inside, to the end\n"
    assert _paths(unclosed) == ["A"]
    shorter_close = "````\n```\n# still inside\n````\n# B\n"
    assert _paths(shorter_close) == ["B"]
    other_char = "```\n~~~\n# inside\n```\n# C\n"
    assert _paths(other_char) == ["C"]
    info_with_backtick = "``` a`b\n# D\n"  # not a fence: a backtick fence's info has none
    assert _paths(info_with_backtick) == ["D"]


def test_raw_html_blocks_and_multi_line_comments_hide_headings_and_prose():
    text = (
        "<!--\n# commented out\nprose in a comment\n-->\n"
        "<details>\n<summary>more</summary>\n\n# inside details\n</details>\n"
        "<PRE>\n# preformatted\n</pre>\n<script>\n# js\n</script>\n<style>\n# css\n</style>\n"
        "<!-- one line --> \n# Real\n\nVisible prose.\n"
    )
    assert _paths(text) == ["Real"]
    assert first_paragraph(text) == "Visible prose."
    assert _paths("<pre>x</pre>\n# After\n") == ["After"]  # opened and closed on one line
    assert _paths("<prelude>\n# Kept\n") == ["Kept"]  # not a <pre> tag


def test_atx_rules_and_setext_text_is_not_a_heading():
    text = (
        "Setext title\n============\n\nSub title\n---------\n\n"
        "#no-space\n    # indented code\n   ### Three spaces ok ###\n####### seven\n#\n## C#\n"
        "# #\n## trailing #s ##   \n"
    )
    hs = headings(text)
    assert [(h.level, h.title) for h in hs] == [
        (3, "Three spaces ok"),
        (2, "C#"),
        (2, "trailing #s"),
    ]
    assert "Setext title" in first_paragraph("Setext title\n============\n")


@pytest.mark.parametrize(
    "sep", ["\r", "\v", "\f", "\x1c", "\x1d", "\x1e", "\x85", "\u2028", "\u2029"]
)
def test_only_newline_ends_a_line_so_no_separator_hides_a_heading(sep):
    text = f"# Visible\n\nprose{sep}# hidden heading{sep}## another\n"
    assert _paths(text) == ["Visible"]
    assert "hidden heading" in first_paragraph(text)  # one line of text, cleaned
    assert sep not in first_paragraph(text)
    assert _paths("# A\r\n## B\r\n") == ["A", "B"]  # a CRLF line ending is still one


def test_titles_are_visible_text_and_slugs_are_built_from_it():
    hs = headings(
        "## [Link text](a.md) and `code`\n## [[target|Label]]\n## *em* __strong__ snake_case\n"
        "## <span>tagged</span> --- dashes\n"
    )
    assert [h.title for h in hs] == [
        "Link text and code",
        "Label",
        "em strong snake_case",
        "tagged --- dashes",
    ]
    assert [h.slug for h in hs] == [
        "link-text-and-code",
        "label",
        "em-strong-snake_case",
        "tagged-dashes",
    ]
    assert visible("[[a]]") == "a"


@pytest.mark.parametrize(
    "bad",
    ["\x1b[31m", "\x00", "\u202e", "\u200b", "\u2028", "\ufeff", "\u2066", "\x7f", "\u061c"],
)
def test_model_facing_text_is_cleaned_of_control_and_invisible_characters(bad):
    text = f"---\ntitle: x\n---\n# Ti{bad}tle\n\n## Sub{bad}section\n\nPro{bad}se here.\n"
    for h in headings(text):
        for field in (h.title, h.slug, h.path):
            assert bad not in field and all(c.isprintable() or c == " " for c in field)
    assert bad not in first_paragraph(text)
    assert bad[0] not in clean(f"a{bad}b") and clean(f"a{bad}b").startswith("a")
    assert clean("tab\there  and\nnewline") == "tab here and newline"


def test_duplicate_titles_are_qualified_by_their_parent_then_counted():
    text = (
        "## Unreleased\n### Added\n### Changed\n## 0.1.0\n### Added\n### Added\n"
        "## Added 2\n## Added\n## added~2 literal\n"
    )
    hs = headings(text)
    assert [h.slug for h in hs] == [
        "unreleased",
        "added",
        "changed",
        "0-1-0",
        "0-1-0/added",
        "0-1-0/added~2",
        "added-2",  # a literal title never collides with a qualified or counted slug
        "added~2",
        "added-2-literal",
    ]
    assert [h.path for h in hs] == [
        "Unreleased",
        "Unreleased/Added",
        "Unreleased/Changed",
        "0.1.0",
        "0.1.0/Added",
        "0.1.0/Added~2",
        "Added 2",
        "Added",
        "added\\~2 literal",  # an escaped ~ cannot read as a counter
    ]
    assert len({h.slug for h in hs}) == len({h.path for h in hs}) == len(hs)
    assert headings(text) == hs  # same text, same answer
    assert headings("# !!!\n")[0].slug == "heading"
    assert _paths("## A/B\n## A\\B\n") == ["A\\/B", "A\\\\B"]


def test_two_h1_headings_are_both_path_segments():
    assert _paths("# One\n## Sub\n# Two\n## Sub\n") == ["One", "One/Sub", "Two", "Two/Sub"]
    assert _paths("Preamble.\n## First\n# Late title\n## Sub\n") == [
        "First",
        "Late title",
        "Late title/Sub",
    ]  # an H1 after another heading is not the document's title


def test_section_extent_runs_to_the_next_heading_of_the_same_or_higher_level():
    hs = {h.path: h for h in headings(DOC)}
    dec = hs["Decision"]
    sec = DOC[dec.start : dec.end]
    assert sec.startswith("## Decision\n") and "### Consequences" in sec
    assert "## Alternatives" not in sec and dec.chars == len(sec)
    alt = hs["Alternatives"]
    assert DOC[alt.start : alt.end].endswith("~~~\n") and alt.end == len(DOC)
    assert hs["Example page"].end == len(DOC)
    empty = headings("## A\ntext\n#\n## B\n")  # an empty heading still ends the section
    assert [h.title for h in empty] == ["A", "B"] and empty[0].chars == len("## A\ntext\n")


def test_find_section_is_exact_by_slug_or_full_path():
    hs = headings(DOC)
    assert [h.slug for h in find_section(hs, "decision")] == ["decision"]
    assert [h.slug for h in find_section(hs, "Decision")] == ["decision"]  # its path
    assert [h.slug for h in find_section(hs, "Decision/Consequences")] == ["consequences"]
    for near in ("DECISION", "decis", " decision", "Example page/Decision", "decision/"):
        assert find_section(hs, near) == []
    same = headings("## x-y\n## X Y\n")  # "x-y" is the first's slug and path: counted once
    assert [h.title for h in find_section(same, "x-y")] == ["x-y"]
    # ambiguous: "one-x" is the nested heading's slug and the second top-level heading's path
    split = headings("## top\n### one-x\n## one-x\n")
    assert [h.path for h in find_section(split, "one-x")] == ["top/one-x", "one-x"]


# -- bounds and time --------------------------------------------------------------------------


def test_a_pathological_heading_line_parses_in_linear_time():
    """The old pattern's overlapping optional groups took 15 s on a 40,000-space line."""
    line = "# a" + " " * 200_000 + "x\n"
    t = time.perf_counter()
    hs = headings(line)
    assert time.perf_counter() - t < 1.0
    assert len(hs) == 1 and len(hs[0].title) <= levels.MAX_TITLE_CHARS
    brackets = "# " + "[" * 200_000 + "\n"
    t = time.perf_counter()
    headings(brackets)
    first_paragraph("x\n" + "[" * 200_000 + "\n")
    assert time.perf_counter() - t < 1.0


def test_fifty_thousand_headings_parse_in_linear_time():
    """About 0.5 s on a laptop; the counter search this replaced was quadratic in the repeats
    (minutes here), so 2 s leaves a loaded CI runner room without hiding a regression."""
    doc = "".join(f"## Same\n### Same\ntext {i}\n" for i in range(25_000))
    t = time.perf_counter()
    hs = headings(doc)
    assert time.perf_counter() - t < 2.0
    assert len(hs) == 50_000 and len({h.slug for h in hs}) == len({h.path for h in hs}) == 50_000


def test_parsing_stops_at_the_bounds_and_says_so(monkeypatch):
    big = "## A\n" + "x\n" * 10 + "## B\n"
    monkeypatch.setattr(levels, "MAX_PARSE_LINES", 5)
    levels.clear_memo()
    p = parse(big)
    assert p.truncated and [h.title for h in p.headings] == ["A"]
    assert p.headings[0].end == p.parsed_chars < len(big)
    monkeypatch.setattr(levels, "MAX_PARSE_LINES", MAX_PARSE_LINES)
    monkeypatch.setattr(levels, "MAX_PARSE_CHARS", 12)
    levels.clear_memo()
    p = parse(big)
    assert p.truncated and p.parsed_chars <= 12 and [h.title for h in p.headings] == ["A"]
    levels.clear_memo()
    assert MAX_PARSE_CHARS == 1 << 20


def test_parse_is_memoised_per_content():
    levels.clear_memo()
    a = parse(DOC)
    assert parse(DOC) is a and parse(DOC + "\n") is not a


