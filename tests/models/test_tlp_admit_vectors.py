"""The shared TLP admission vectors (ADR-0038 decision 5) are what ``admit`` says.

Another implementation of the rule (the lab gateway's) is held to
``conformance/fixtures/tlp_admit_vectors.json``, so the file is generated here from
:func:`homelabnext.registry.model_tlp.admit` itself and must match it byte for byte.  To
regenerate after a deliberate change to the rule: ``HNX_REGEN_TLP_VECTORS=1 pytest`` on this file.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

from homelabnext import tlp
from homelabnext.registry.model_tlp import admit

VECTORS = Path(__file__).resolve().parents[2] / "conformance/fixtures/tlp_admit_vectors.json"

_TERMS = {"retention": "none", "training": "none"}
#: one role of each kind admit tells apart: stays in the lab, leaves it (clear), leaves it raised
#: to green, and a local role whose fallback leaves the lab (chain-inclusive)
ROLES = {
    "local": {"bindings": [{"backend": "svc:local-engine", "model": "m-local"}]},
    "cloud": {"bindings": [{"backend": "svc:cloud-api", "model": "m-cloud", "leaves_lab": True}]},
    "cloud-green": {
        "tlp_ceiling": "green",
        "bindings": [
            {
                "backend": "svc:cloud-api",
                "model": "m-green",
                "leaves_lab": True,
                "provider_terms": _TERMS,
            }
        ],
    },
    "local-cloud-fallback": {
        "bindings": [{"backend": "svc:local-engine", "model": "m-local"}],
        "fallback": "mdl:cloud",
    },
}
#: None = no header; the rest are header values, lenient spellings and non-labels included
HEADERS = [
    None, "red", "amber+strict", "amber", "green", "clear", "white", "TLP:GREEN", " tlp:Clear ",
    "Green", "AMBER+STRICT", "TLP:WHITE", "\tred\r\n", "tlp: red", "tlp:tlp:red", "amber-strict",
    chr(0xA0) + "red", "purple", "", "tlp:", "r" + chr(0xE8) + "d",
]  # fmt: skip
SENDERS = ["red", "clear", "green"]


def build() -> dict:
    vectors = []
    for role in ROLES:
        for sender in SENDERS:
            for header in HEADERS:
                a = admit(ROLES, role, header, sender=tlp.parse_stored(sender))
                vectors.append(
                    {"role": role, "sender_ceiling": sender, "header": header} | a.record()
                )
    return {
        "description": (
            "Test vectors for the per-request TLP admission rule (ADR-0033 decision 11, ADR-0038 "
            "decision 5), generated by tests/models/test_tlp_admit_vectors.py from "
            "homelabnext.registry.model_tlp.admit over the role table in `roles`. header null = "
            "the request carried no X-HNX-TLP field. Each vector's last six fields are "
            "Admission.record(): role (mdl:<name>), allowed, reason, label (the label judged), "
            "ceiling (the role's) and leaves_lab (chain-inclusive). Labels least to most "
            "restrictive: " + ", ".join(tlp.LABELS) + "."
        ),
        "labels": list(tlp.LABELS),
        "roles": ROLES,
        "vectors": vectors,
    }


def _text() -> str:
    return json.dumps(build(), indent=1, ensure_ascii=False) + "\n"


def test_the_vectors_file_is_what_admit_says():
    if os.environ.get("HNX_REGEN_TLP_VECTORS") == "1":
        VECTORS.write_text(_text(), encoding="utf-8")
    assert VECTORS.read_text(encoding="utf-8") == _text(), (
        "conformance/fixtures/tlp_admit_vectors.json is stale: rerun this test with "
        "HNX_REGEN_TLP_VECTORS=1 after a deliberate change to admit"
    )


def test_the_vectors_cover_every_outcome_and_both_role_kinds():
    vs = build()["vectors"]
    assert {v["reason"] for v in vs} == {"within-ceiling", "above-ceiling", "unlabelled"}
    assert {(v["leaves_lab"], v["ceiling"]) for v in vs} == {
        (False, "red"), (True, "clear"), (True, "green"),
    }  # fmt: skip
    chain = {v["leaves_lab"] for v in vs if v["role"] == "mdl:local-cloud-fallback"}
    assert chain == {True}, "a local role with a cloud fallback leaves the lab"
