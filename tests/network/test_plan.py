"""``plan``: create / update / delete / unchanged, object-level summaries, and safe deletion."""

from __future__ import annotations

import json

from netutil import render

from homelabnext.network import adapters, build_ir
from homelabnext.network.plan import compute_plan, write_rendered


def test_empty_current_means_everything_is_created(ir):
    rendered = render("unifi", ir)
    plan = compute_plan("unifi", rendered, None)
    assert plan.changed
    assert plan.counts() == {"create": len(rendered), "update": 0, "delete": 0, "unchanged": 0}
    assert plan.render().startswith(f"plan (unifi): {len(rendered)} to create")


def test_changed_zone_shows_an_object_level_update(doc, registry, tmp_path):
    write_rendered(render("unifi", build_ir(doc, registry)), tmp_path)
    next(z for z in doc["zones"] if z["id"] == "edge")["dhcp"]["lease_hours"] = 6
    plan = compute_plan("unifi", render("unifi", build_ir(doc, registry)), tmp_path)
    nets = next(c for c in plan.changes if c.path == "networks.json")
    assert nets.action == "update"
    assert [(o.key, o.action) for o in nets.objects] == [("hnx-edge", "update")]
    assert '-      "dhcpd_leasetime": 43200,' in nets.diff
    assert '+      "dhcpd_leasetime": 21600,' in nets.diff
    text = plan.render()
    assert "~ update networks.json" in text and "    ~ hnx-edge" in text
    assert "--- current/networks.json" in text and "+++ desired/networks.json" in text


def test_new_rule_is_a_create_object(doc, registry, tmp_path):
    write_rendered(render("unifi", build_ir(doc, registry)), tmp_path)
    doc["firewall"]["zone_to_zone"].append({"from": "data", "to": "mgmt", "action": "deny"})
    plan = compute_plan("unifi", render("unifi", build_ir(doc, registry)), tmp_path)
    rules = next(c for c in plan.changes if c.path == "firewall-rules.json")
    assert ("hnx-zone_to_zone-5", "create") in [(o.key, o.action) for o in rules.objects]


def test_stale_generated_file_is_a_delete_but_foreign_files_are_left_alone(ir, tmp_path):
    rendered = render("dnsmasq", ir)
    write_rendered(rendered, tmp_path)
    (tmp_path / "etc/dnsmasq.d/99-old.conf").write_text(
        "# Generated by `hnx site render --adapter dnsmasq`\nx\n"
    )
    (tmp_path / "etc/dnsmasq.d/00-hand-written.conf").write_text("port=5353\n")
    plan = compute_plan("dnsmasq", rendered, tmp_path)
    actions = {c.path: c.action for c in plan.changes}
    assert actions["etc/dnsmasq.d/99-old.conf"] == "delete"
    assert "etc/dnsmasq.d/00-hand-written.conf" not in actions


def test_prune_removes_only_stale_generated_files(ir, tmp_path):
    rendered = render("dnsmasq", ir)
    write_rendered(rendered, tmp_path)
    stale = tmp_path / "etc/dnsmasq.d/99-old.conf"
    stale.write_text("# Generated by `hnx site render --adapter dnsmasq`\nx\n")
    keep = tmp_path / "etc/dnsmasq.d/00-hand-written.conf"
    keep.write_text("port=5353\n")
    assert write_rendered(rendered, tmp_path) == []
    assert write_rendered(rendered, tmp_path, prune=True) == ["etc/dnsmasq.d/99-old.conf"]
    assert not stale.exists() and keep.exists()


def test_json_form_is_machine_readable(ir):
    plan = compute_plan("linux", render("linux", ir), None)
    body = json.loads(json.dumps(plan.to_dict()))
    assert body["changed"] is True and body["adapter"] == "linux"
    assert {c["action"] for c in body["changes"]} == {"create"}


def test_summary_only_omits_diffs(ir):
    text = compute_plan("zonefile", render("zonefile", ir), None).render(diffs=False)
    assert "+++ desired" not in text and "+ create var/lib/hnx/zones/example.internal.zone" in text


#: the controller adapter, whose payloads are object documents (name the slot, not the product)
[CONTROLLER] = adapters.names_for("switch")


def test_a_created_and_a_deleted_payload_list_their_objects(ir, tmp_path):
    rendered = adapters.get(CONTROLLER).render(ir)
    nets = next(
        c for c in compute_plan(CONTROLLER, rendered, None).changes if c.path == "networks.json"
    )
    names = [o["name"] for o in json.loads(rendered["networks.json"])["objects"]]
    assert nets.action == "create" and names
    assert [(o.key, o.action) for o in nets.objects] == [(n, "create") for n in names]
    assert f"    + {names[0]}" in compute_plan(CONTROLLER, rendered, None).render()
    write_rendered(rendered, tmp_path)
    gone = {k: v for k, v in rendered.items() if k != "networks.json"}
    nets = next(
        c for c in compute_plan(CONTROLLER, gone, tmp_path).changes if c.path == "networks.json"
    )
    assert nets.action == "delete"
    assert [(o.key, o.action) for o in nets.objects] == [(n, "delete") for n in names]
