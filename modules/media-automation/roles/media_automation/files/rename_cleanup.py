"""Cleans up messy torrent-release-style filenames (brackets, duplicated
extensions, site tags) across the whole Sonarr/Radarr library, using each
app's own /rename preview endpoint to compute the CORRECT clean name
(Sonarr/Radarr's own naming-format logic, which is reliable) but doing the
actual file operation directly on disk with a real os.rename() rather than
trusting the RenameFiles/RenameMovieFiles API command.

That command was tried first and confirmed unreliable live (2026-07-18):
it doesn't consistently perform the rename for bulk calls, and even when
it does work, it creates a NEW hardlink with the clean name without ever
unlinking the old messy one, and never updates its own database's tracked
path either way -- meaning /rename keeps reporting the same "pending"
work forever. A plain os.rename() is atomic on the same filesystem (no
data copy), preserves the same inode, and Sonarr/Radarr's own filesystem
scan reliably re-matches the renamed file via its own already-correctly-
formatted S/E (or movie) markers, so an explicit Rescan command afterward
is enough to bring each app's database back in sync.

Run via media-rename-cleanup.timer (daily). Safe to run indefinitely --
every operation is idempotent (skips if source is already gone or
destination already exists, never overwrites).

API keys are read directly from each app's own config.xml at runtime
(not vault-templated) -- these are auto-generated by each app itself, not
something this repo's Ansible roles set, so this stays correct even if a
key is ever rotated by hand.
"""

import json
import os
import re
import sys
import time
import urllib.error
import urllib.request

CONFIG_ROOT = os.environ.get("APP_CONFIG_ROOT", "/var/lib/hnx-modules/media-automation/config")
SONARR_CONFIG = os.path.join(CONFIG_ROOT, "sonarr", "config.xml")
RADARR_CONFIG = os.path.join(CONFIG_ROOT, "radarr", "config.xml")
LIBRARY_ROOT = os.environ.get("MEDIA_ROOT", "/srv/media")
SONARR_URL = os.environ.get("SONARR_URL", "")
RADARR_URL = os.environ.get("RADARR_URL", "")
# the media server's library refresh is optional: its address and an API key the operator minted
MEDIA_SERVER_BASE = os.environ.get("MEDIA_SERVER_URL", "")
MEDIA_SERVER_KEY = os.environ.get("MEDIA_SERVER_ACCESS_KEY", "")


def read_api_key(config_path: str) -> str:
    with open(config_path) as f:
        content = f.read()
    match = re.search(r"<ApiKey>([^<]+)</ApiKey>", content)
    if not match:
        raise RuntimeError(f"No ApiKey found in {config_path}")
    return match.group(1)


def api(base, key, path, method="GET", body=None, retries=2, backoff_s=5):
    """CORRECTED 2026-09-09 -- the retry below is real defensive hardening but it was NOT
    the actual fix for TASK-20260908-17. The `HTTP Error 401: Unauthorized` that repeatedly
    killed the whole script was misattributed to Radarr from journalctl's own out-of-order
    stdout/stderr interleaving (stderr flushes immediately, stdout is buffered, so the
    exception line prints BEFORE the later "[radarr] TOTAL" success line that actually
    proves Radarr's own calls all succeeded). Reproduced live on demand (15:14 PDT, nowhere
    near the original 04:02 timing) and isolated to `trigger_media_server_refresh()` below,
    which makes its OWN unwrapped `urlopen` call -- the media server's single stored API key
    ("Jellyseerr", DateCreated 2026-07-17) is genuinely, persistently dead (tested directly
    against both /Library/Refresh and /System/Info, 401 both times; ApiKeys table has no
    active/revoked column at all, so nothing on the DB side even hints at why). The REAL
    fix is at the bottom of this file: the refresh call is no longer allowed to crash the
    whole script over a nice-to-have nudge The media server's own filesystem scan will eventually
    do anyway. This retry stays as legitimate hardening for Sonarr/Radarr's OWN calls
    (a real transient failure there would still be worth absorbing), it just wasn't what
    this incident needed."""
    data = json.dumps(body).encode() if body is not None else None
    headers = {"X-Api-Key": key}
    if data:
        headers["Content-Type"] = "application/json"
    req = urllib.request.Request(f"{base}{path}", data=data, headers=headers, method=method)
    last_exc = None
    for attempt in range(retries + 1):
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                return json.loads(resp.read())
        except (urllib.error.HTTPError, urllib.error.URLError) as e:
            last_exc = e
            if attempt < retries:
                print(
                    f"[!] {base}{path} attempt {attempt + 1}/{retries + 1} failed "
                    f"({e}) -- retrying in {backoff_s}s",
                    file=sys.stderr,
                )
                time.sleep(backoff_s)
    raise last_exc


def real_root(reported_path: str, real_root_prefix: str) -> str:
    """Sonarr/Radarr's individual series/movie records can carry a STALE
    root path left over from a config transplant/migration (confirmed live
    2026-07-18: reported "/data/shows/X", but the actual configured Root
    Folder -- and the only thing that ever really existed -- is
    "/media/shows"). Only the final folder-name segment is trustworthy --
    combine that with the known-correct real host mount prefix instead of
    trusting the full reported path."""
    folder_name = os.path.basename(reported_path.rstrip("/"))
    return os.path.join(real_root_prefix, folder_name)


def _inside(path: str, root: str) -> bool:
    root = os.path.realpath(root)
    real = os.path.realpath(path)
    return real == root or real.startswith(root + os.sep)


def rename_on_disk(root_path: str, old_relative: str, new_relative: str) -> bool:
    """Rename inside root_path only. The relative names come from an API: a name that leaves the
    series/movie folder (.., an absolute path), a link, or a folder outside the library is refused."""
    old_full = os.path.normpath(os.path.join(root_path, old_relative))
    new_full = os.path.normpath(os.path.join(root_path, new_relative))
    base = os.path.normpath(root_path)
    for p in (old_full, new_full):
        if not p.startswith(base + os.sep) or not _inside(os.path.dirname(p), LIBRARY_ROOT):
            print(f"  [!] refusing a path outside the library folder: {p}", file=sys.stderr)
            return False
    if old_full == new_full:
        return False
    if os.path.islink(old_full):
        print(f"  [!] refusing a link: {old_full}", file=sys.stderr)
        return False
    if not os.path.exists(old_full):
        print(f"  [!] source missing, skipping: {old_full}", file=sys.stderr)
        return False
    if os.path.exists(new_full):
        print(f"  [!] destination already exists, skipping: {new_full}", file=sys.stderr)
        return False
    os.makedirs(os.path.dirname(new_full), exist_ok=True)
    os.rename(old_full, new_full)
    return True


def process_sonarr(key: str):
    series_list = api(SONARR_URL, key, "/api/v3/series")
    total = 0
    for s in series_list:
        preview = api(SONARR_URL, key, f"/api/v3/rename?seriesId={s['id']}")
        if not preview:
            continue
        root = real_root(s["path"], os.path.join(LIBRARY_ROOT, "shows"))
        renamed = 0
        for p in preview:
            if rename_on_disk(root, p["existingPath"], p["newPath"]):
                renamed += 1
        if renamed:
            api(
                SONARR_URL,
                key,
                "/api/v3/command",
                method="POST",
                body={"name": "RescanSeries", "seriesId": s["id"]},
            )
        if renamed:
            print(f"[sonarr] {s['title']}: {renamed} file(s) renamed")
        total += renamed
    print(f"[sonarr] TOTAL: {total} file(s) renamed")


def process_radarr(key: str):
    movies = api(RADARR_URL, key, "/api/v3/movie")
    total = 0
    for m in movies:
        if not m.get("hasFile"):
            continue
        preview = api(RADARR_URL, key, f"/api/v3/rename?movieId={m['id']}")
        if not preview:
            continue
        root = real_root(m["path"], os.path.join(LIBRARY_ROOT, "movies"))
        renamed = 0
        for p in preview:
            if rename_on_disk(root, p["existingPath"], p["newPath"]):
                renamed += 1
        if renamed:
            api(
                RADARR_URL,
                key,
                "/api/v3/command",
                method="POST",
                body={"name": "RescanMovie", "movieIds": [m["id"]]},
            )
        if renamed:
            print(f"[radarr] {m['title']}: {renamed} file(s) renamed")
        total += renamed
    print(f"[radarr] TOTAL: {total} file(s) renamed")


def trigger_media_server_refresh():
    """The media server scans the filesystem independently of the apps' own databases and needs
    its own nudge to pick up renamed files. Optional: only when MEDIA_SERVER_URL and
    MEDIA_SERVER_ACCESS_KEY are set (its own scan finds the files on its schedule regardless)."""
    if not (MEDIA_SERVER_BASE and MEDIA_SERVER_KEY):
        print("[media-server] no URL/key configured, skipping refresh")
        return
    req = urllib.request.Request(
        f"{MEDIA_SERVER_BASE}/Library/Refresh",
        headers={"X-Emby-Token": MEDIA_SERVER_KEY},
        method="POST",
    )
    urllib.request.urlopen(req, timeout=30)
    print("[media-server] library refresh triggered")


def main() -> int:
    try:
        process_sonarr(read_api_key(SONARR_CONFIG))
        process_radarr(read_api_key(RADARR_CONFIG))
    except Exception as e:
        print(f"rename-cleanup failed: {e}", file=sys.stderr)
        return 1
    # 2026-09-09 (TASK-20260908-17): deliberately a SEPARATE try/except from the one above --
    # this is a nice-to-have nudge, not the job. The media server's own filesystem scan finds renamed
    # files on its regular schedule regardless of whether this fires; the primary job (the
    # actual renames, both apps) already succeeded and printed its own totals by this point.
    # A dead reused API key (confirmed live: the media server's single stored "Jellyseerr" key 401s
    # against its own API entirely, not just this endpoint -- needs a fresh key minted via
    # the The media server dashboard, which this script cannot do headlessly) must not fail the whole
    # service and mask that the real work completed.
    try:
        trigger_media_server_refresh()
    except Exception as e:
        print(
            f"[media-server] library refresh failed (non-fatal, renames already done): {e}",
            file=sys.stderr,
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
