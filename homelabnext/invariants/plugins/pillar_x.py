# ---- X-03 -----------------------------------------------------------------------------------

# A pinned ``$id`` is one of:
#   .../v1          .../v1.2          .../v1/...        (SemVer-style with the v- prefix)
#   .../1.0         .../2.1           .../1.2.3         (trailing dotted version, the repo convention
#                                                       enforced by ``tools/schema_check.py``)
#   ...@1           ...@1.2.3                           (version suffix after @)
_VERSION_ID = re.compile(r"(/v\d+(?:\.\d+)*(?:/|$|\.)|/\d+\.\d+(?:\.\d+)?(?:/|$)|@\d+(?:\.\d+)*$)")
_VERSION_FIELD = re.compile(r"^\d+\.\d+(\.\d+)?$")


_FRONTMATTER = re.compile(r"\A---\n(.*?)\n---\s*(?:\n|\Z)", re.S)


def _load(path: pathlib.Path):
    """Load a schema instance from ``.json``, ``.yaml``/``.yml`` or ``.md`` (YAML frontmatter).

    Used only by :func:`_x03_generic`, for a tree without ``tools/schema_check.py``; a tree with
    it is checked by it alone (its loader keeps timestamps as strings, this one does not).
    """
    text = path.read_text()
    if path.suffix == ".json":
        return json.loads(text)
    if path.suffix == ".md":
        m = _FRONTMATTER.match(text)
        if m is None:
            raise ValueError(f"{path}: no YAML frontmatter")
        return _yaml_safe_load(m.group(1))
    return _yaml_safe_load(text)


def _build_registry(schemas: list[pathlib.Path]):
    r"""Build a ``referencing`` Registry so that cross-schema ``$ref``\s resolve offline.

    Without a registry a validator carrying a reference like
    ``https://schemas.example.internal/.../ids/logical-id/1.0#/$defs/...`` falls back to
    HTTP retrieval, which turns an offline check into either a network call or an
    ``Unresolvable`` on an air-gapped runner. Register every schema under its ``$id``.
    Returns ``None`` on import failure (fall back to a bare validator).
    """
    from homelabnext.schema_registry import registry_of

    docs = []
    for sp in schemas:
        try:
            docs.append(json.loads(sp.read_text()))
        except Exception:
            continue
    try:
        return registry_of(docs)
    except ImportError:
        return None


def x03(ctx: Context) -> CheckResult:
    """X-03.  A tree that carries ``tools/schema_check.py`` (this repository) is judged by it,
    under ``--strict``: one implementation of which files are schemas (every ``*.json``, the
    OCSF ``<class>.v1.json`` and ``service.json`` included), which files are a schema's examples
    and negatives, and what a pinned ``$id`` is, so the invariant certifies exactly what CI
    checks.  Any other tree gets the generic layout check (:func:`_x03_generic`)."""
    if (ctx.root / "tools" / "schema_check.py").is_file():
        return _tool_check(
            ctx,
            "tools/schema_check.py",
            ["--strict", "--root", str(ctx.root)],
            "schema_check --strict: schemas pinned, examples valid, negatives rejected",
        )
    return _x03_generic(ctx)


def _x03_generic(ctx: Context) -> CheckResult:
    """X-03 for an adopter's tree without the repository checker: the layout conventions in
    this module's docstring (``NAME.schema.json``, ``x-version`` or a ``/vN`` ``$id``)."""
    sdir = ctx.root / "schemas"
    # ``_frozen/`` holds version-stamped snapshots that intentionally pre-date the current
    # ``$id``/``x-version`` pinning convention - the frozen tree is for baseline comparison,
    # not for re-validation. ``tools/schema_check.py`` skips it the same way.
    schemas = (
        sorted(p for p in sdir.rglob("*.schema.json") if "_frozen" not in p.parts)
        if sdir.is_dir()
        else []
    )
    if not schemas:
        return CheckResult(SKIP, "no schemas/ tree")
    try:
        import jsonschema
    except ImportError:
        return CheckResult(ERROR, "jsonschema is not installed")
    registry = _build_registry(schemas)
    problems = []
    for sp in schemas:
        rel = sp.relative_to(ctx.root).as_posix()
        name = sp.name[: -len(".schema.json")]
        try:
            schema = json.loads(sp.read_text())
            jsonschema.Draft202012Validator.check_schema(schema)
        except Exception as ex:
            problems.append(f"{rel}: not a valid schema ({type(ex).__name__})")
            continue
        if "$schema" not in schema or "$id" not in schema:
            problems.append(f"{rel}: needs $schema and $id")
        ver = schema.get("x-version")
        if not (isinstance(ver, str) and _VERSION_FIELD.match(ver)) and not _VERSION_ID.search(
            str(schema.get("$id", ""))
        ):
            problems.append(f"{rel}: not version-pinned (x-version or /vN in $id)")
        if registry is not None:
            validator = jsonschema.Draft202012Validator(schema, registry=registry)
        else:
            validator = jsonschema.Draft202012Validator(schema)
        # Schemas tagged ``"x-defs-only": true`` hold shared ``$defs`` and are referenced from
        # other schemas; they ship no instance of their own. ``tools/schema_check.py`` exempts
        # them the same way (ADR-0001).
        defs_only = bool(schema.get("x-defs-only"))
        exts = ("json", "yml", "yaml", "md")
        good: list[pathlib.Path] = []
        bad: list[pathlib.Path] = []
        for ext in exts:
            good += sorted((sp.parent / "examples").glob(f"{name}.*.{ext}"))
            bad += sorted((sp.parent / "negative").glob(f"{name}.*.{ext}"))
        if not defs_only and not good:
            problems.append(f"{rel}: no example in examples/{name}.*")
        if not defs_only and not bad:
            problems.append(f"{rel}: no negative in negative/{name}.*")
        for g in good:
            try:
                errs = list(validator.iter_errors(_load(g)))
            except Exception as ex:
                problems.append(
                    f"{g.relative_to(ctx.root).as_posix()}: could not validate "
                    f"({type(ex).__name__}: {str(ex)[:80]})"
                )
                continue
            if errs:
                problems.append(
                    f"{g.relative_to(ctx.root).as_posix()}: example invalid ({errs[0].message[:80]})"
                )
        for b in bad:
            try:
                is_valid = validator.is_valid(_load(b))
            except Exception as ex:
                problems.append(
                    f"{b.relative_to(ctx.root).as_posix()}: could not validate "
                    f"({type(ex).__name__}: {str(ex)[:80]})"
                )
                continue
            if is_valid:
                problems.append(f"{b.relative_to(ctx.root).as_posix()}: negative was ACCEPTED")
    if problems:
        return CheckResult(FAIL, "; ".join(problems))
    return CheckResult(PASS, f"{len(schemas)} schemas pinned, examples valid, negatives rejected")


# ---- X-04 -----------------------------------------------------------------------------------


#: directories of ``conformance/`` that hold harness code, not a capability's test
HARNESS_DIRS = frozenset({"suites", "protocols", "fakes", "targets", "fixtures"})


def _capabilities(root: pathlib.Path) -> list[str] | None:
    """The declared capabilities (the one validated reader, ``conform.registry``), else the
    capability directories of ``conformance/``, else None.  Raises ``ConformError`` when
    ``capabilities.yml`` exists but declares nothing usable."""
    from homelabnext.conform.registry import declared_capabilities

    declared = declared_capabilities(root)
    if declared is not None:
        return declared
    conf = root / "conformance"
    if conf.is_dir():
        return sorted(
            d.name
            for d in conf.iterdir()
            if d.is_dir() and not d.name.startswith(("_", ".")) and d.name not in HARNESS_DIRS
        )
    return None


def x04(ctx: Context) -> CheckResult:
    from homelabnext.conform.registry import ConformError

    try:
        caps = _capabilities(ctx.root)
    except ConformError as exc:  # a file that declares nothing must not pass with 0 capabilities
        return CheckResult(ERROR, str(exc))
    if caps is None:
        return CheckResult(SKIP, "no capabilities.yml or conformance/ tree")
    missing = [c for c in caps if not list((ctx.root / "conformance" / c).glob("test_*.py"))]
    if missing:
        return CheckResult(FAIL, f"capabilities without a conformance test: {', '.join(missing)}")
    return CheckResult(PASS, f"{len(caps)} capabilities, each with a conformance test")


# ---- X-06 -----------------------------------------------------------------------------------

DET_MAPS = ("detections/det_map.yml", "det_map.yml")


def _det_map(root: pathlib.Path) -> tuple[str, dict] | None:
    """(map path, map) from the first det map found."""
    for cand in DET_MAPS:
        mp = root / cand
        if mp.exists():
            return cand, _yaml_safe_load(mp.read_text()) or {}
    return None


def x06(ctx: Context) -> CheckResult:
    # One rule, one implementation: the same file set and scanner as `detections lint-ids`.
    from ...detections import lint as det_lint

    files = det_lint.find_agent_files(ctx.root)
    if not files:
        return CheckResult(SKIP, "no charters/profiles/decision specs/schedules to lint")
    found = _det_map(ctx.root)
    map_name, det_map = found if found else ("", None)
    if det_map is not None:
        det_map = {"entries": det_map.get("entries") or {}, "retired": det_map.get("retired") or []}
    problems = [
        p.removeprefix(f"{ctx.root.as_posix()}/")
        for p in det_lint.lint_agent_ids(files, det_map, map_name or "the det map")
    ]
    if problems:
        return CheckResult(FAIL, "; ".join(problems[:20]))
    return CheckResult(PASS, f"{len(files)} spec files use logical detection ids only")


def _server(id_):
    def fn(ctx: Context) -> CheckResult:
        return CheckResult(SKIP, f"SERVER: {SERVER_ONLY[id_]}")

    return fn


def register(reg: Registry) -> None:
    reg.register(Check("X-01", "no raw endpoint literals outside the registry", x01))
    reg.register(Check("X-03", "schemas version-pinned; examples valid; negatives rejected", x03))
    reg.register(Check("X-04", "every capability has a conformance test", x04))
    reg.register(Check("X-05", "role linter reports clean", x05))
    reg.register(Check("X-06", "detection ids in specs are logical, never raw rule numbers", x06))
    reg.register(
        Check("X-11", "product names only in their provider modules, site config and prose", x11)
    )
    reg.register(Check("X-12", "no non-primary registry row is past its until", x12))
    for id_ in SERVER_ONLY:
        reg.register(Check(id_, SERVER_ONLY[id_], _server(id_)))
