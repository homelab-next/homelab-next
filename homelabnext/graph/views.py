"""Navigation pages for the graph: ``docs/graph/README.md`` and one index page per node kind.

``graph.json`` is the data; these pages only help a reader (on GitHub or in an Obsidian vault
opened at ``docs/``) walk it.  Each node is one line: its id, title, a relative link to the file
that defines it, and its outgoing edges grouped by type.  A node with a page of its own under
``docs/`` (a system page, a capability page, an ADR) is a path-qualified ``[[folder/page|label]]``
wiki-link; every other node links its kind's index page, so Obsidian's graph shows the typed
structure.  Retired, superseded and incorporated records are listed under **Archive**.
"""

from __future__ import annotations

from .model import Graph, Node
from .query import is_active
from .vocab import EDGE_TYPES, NODE_KINDS

_HEADER = "<!-- Generated by `hnx graph build` from the repository. Do not edit. -->\n"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _page_of(graph: Graph) -> dict[str, str]:
    """node id -> its own docs page (vault-relative, no ``.md``) when it has one."""
    out: dict[str, str] = {}
    for n in graph.nodes.values():
        if n.kind in ("doc", "adr") and n.path.startswith("docs/") and n.path.endswith(".md"):
            page = n.path[len("docs/") : -len(".md")]
            out[n.id] = page
            for e in graph.out_edges(n.id):
                if e.type == "documents":
                    out.setdefault(e.dst, page)
    return out


def _ref(nid: str, graph: Graph, pages: dict[str, str]) -> str:
    if nid in pages:
        return f"[[{pages[nid]}|{nid}]]"
    node = graph.nodes.get(nid)
    kind = node.kind if node else ""
    return f"[[graph/{kind}|{nid}]]" if kind else f"`{nid}`"


def _line(n: Node, graph: Graph, pages: dict[str, str]) -> str:
    head = f"- **`{n.id}`**"
    if n.title and n.title != n.id.split(":", 1)[-1]:
        head += f" {_cell(n.title)}"
    if n.path:
        head += f" ([source](../../{n.path}))"
    if n.id in pages:
        head += f" [[{pages[n.id]}|page]]"
    groups: dict[str, list[str]] = {}
    for e in graph.out_edges(n.id):
        groups.setdefault(e.type, [])
        ref = _ref(e.dst, graph, pages)
        if ref not in groups[e.type]:
            groups[e.type].append(ref)
    rows = [head]
    rows += [f"  - {t}: {', '.join(refs)}" for t, refs in sorted(groups.items())]
    return "\n".join(rows)


def _kind_page(kind: str, graph: Graph, pages: dict[str, str]) -> str:
    nodes = graph.of_kind(kind)
    live = [n for n in nodes if is_active(n)]
    archive = [n for n in nodes if not is_active(n)]
    form, source = NODE_KINDS.get(kind, ("", ""))
    out = [
        _HEADER,
        f"# Graph: `{kind}` nodes",
        "",
        f"{len(nodes)} node(s), id form `{form}`, defined by {source}. "
        "[All kinds](README.md) ([[graph/README|graph]]).",
        "",
    ]
    out += [_line(n, graph, pages) for n in live]
    if archive:
        out += [
            "",
            "## Archive",
            "",
            "Retired, superseded or incorporated: kept for history, left out of queries.",
        ]
        out += [""] + [_line(n, graph, pages) for n in archive]
    return "\n".join(out).rstrip() + "\n"


def _index(graph: Graph) -> str:
    kinds = graph.kinds()
    types = graph.edge_types()
    archived = [n for n in graph.nodes.values() if not is_active(n)]
    out = [
        _HEADER,
        "# Knowledge graph",
        "",
        f"{len(graph.nodes)} nodes and {len(graph.edges)} typed edges, every one read from a field of "
        "a source file (`source` names it). The data is [graph.json](graph.json); how it is built, "
        "checked and queried: [the graph guide](../graph.md) ([[graph]]).",
        "",
        "## Nodes by kind",
        "",
        "| kind | nodes | id form | defined by |",
        "|---|---|---|---|",
    ]
    for k, c in kinds.items():
        form, source = NODE_KINDS.get(k, ("", ""))
        out.append(
            f"| [{k}]({k}.md) ([[graph/{k}\\|{k}]]) | {c} | `{_cell(form)}` | {_cell(source)} |"
        )
    out += [
        "",
        "## Edges by type",
        "",
        "| type | edges | from | to | asserted by |",
        "|---|---|---|---|---|",
    ]
    for t, c in types.items():
        src, dst, by = EDGE_TYPES.get(t, ("", "", ""))
        out.append(f"| `{t}` | {c} | {_cell(src)} | {_cell(dst)} | {_cell(by)} |")
    out += ["", "## Archive", ""]
    if archived:
        out += [f"- `{n.id}` {_cell(n.title)} ([[graph/{n.kind}|{n.kind}]])" for n in archived]
    else:
        out.append("No retired, superseded or incorporated records.")
    return "\n".join(out).rstrip() + "\n"


def render_views(graph: Graph) -> dict[str, str]:
    pages = _page_of(graph)
    out = {"README.md": _index(graph)}
    for kind in graph.kinds():
        out[f"{kind}.md"] = _kind_page(kind, graph, pages)
    return out
