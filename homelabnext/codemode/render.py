#: the public example the committed goldens are generated from, and where they live
DEFAULT_MANIFEST = "examples/broker/manifest.yml"
DEFAULT_OUT = "examples/codemode"
FILES = ("search.json", "stubs.pyi", "types.d.ts")
GENERATOR = f"{MARKER} codemode gen"
SPDX = "SPDX-License-Identifier: Apache-2.0"
#: the repository's ruff line length, which the committed stubs are linted at
LINE_LENGTH = 100
_PY_TYPES = {
    "string": "str",
    "integer": "int",
    "number": "float",
    "boolean": "bool",
    "null": "None",
}
_TS_TYPES = {
    "string": "string",
    "integer": "number",
    "number": "number",
    "boolean": "boolean",
    "null": "null",
}


def _marker(model: ProfileModel) -> str:
    return (
        f"{GENERATOR} from broker manifest {model.source} for {model.profile} - do not edit; "
        f"{model.digest}"
    )


def _union(parts: Iterable[str], empty: str) -> str:
    seen = list(dict.fromkeys(parts))
    if "unknown" in seen or "Any" in seen:
        return "unknown" if "unknown" in seen else "Any"
    return " | ".join(seen) or empty


def _alternatives(schema: Mapping[str, Any]) -> list[Any] | None:
    for key in ("oneOf", "anyOf"):
        if isinstance(schema.get(key), list):
            return schema[key]
    t = schema.get("type")
    if isinstance(t, list):
        return [dict(schema, type=x) for x in t]
    return None


def _open_value(schema: Mapping[str, Any]) -> Any:
    """What ``additionalProperties`` admits: False (nothing), True (anything) or a schema."""
    ap = schema.get("additionalProperties", True)
    return ap if isinstance(ap, Mapping | bool) else True


# ------------------------------------------------------------------ TypeScript
def ts_type(schema: Any) -> str:
    """The TypeScript type of a JSON Schema."""
    if not isinstance(schema, Mapping):
        return "unknown"
    if "const" in schema:
        return json.dumps(schema["const"])
    if isinstance(schema.get("enum"), list):
        return _union((json.dumps(v) for v in schema["enum"]), "never")
    alts = _alternatives(schema)
    if alts is not None:
        return _union((ts_type(a) for a in alts), "never")
    t = schema.get("type")
    if t in _TS_TYPES:
        return _TS_TYPES[t]
    if t == "array":
        inner = ts_type(schema.get("items", {}))
        return f"({inner})[]" if " " in inner else f"{inner}[]"
    if t == "object":
        return _ts_object(schema)
    return "unknown"


def _ts_object(schema: Mapping[str, Any]) -> str:
    props = schema.get("properties") or {}
    ap = _open_value(schema)
    if not props:
        if ap is False:
            return "Record<string, never>"
        return f"Record<string, {ts_type(ap) if isinstance(ap, Mapping) else 'unknown'}>"
    required = set(schema.get("required", []))
    fields = [
        f"{n if n.isidentifier() else json.dumps(n)}{'' if n in required else '?'}: "
        f"{ts_type(props[n])}"
        for n in sorted(props)
    ]
    if ap is not False:
        fields.append("[key: string]: unknown")
    return "{ " + "; ".join(fields) + " }"


def _ts_result_types(model: ProfileModel) -> list[str]:
    out = []
    for name, schema in _result_types(model).items():
        props, req = schema["properties"], set(schema.get("required", []))
        out.append(f"interface {name} {{")
        out += [f"  {n}{'' if n in req else '?'}: {ts_type(props[n])};" for n in sorted(props)]
        out += ["}", ""]
    return out


def _ts_args(m: Method) -> str:
    props = m.params.get("properties") or {}
    if not props and _open_value(m.params) is False:
        return ""
    optional = not set(m.params.get("required", []))
    return f"args{'?' if optional else ''}: {_ts_object(dict(m.params, type='object'))}"


def _ts_returns(m: Method) -> str:
    return _result_name(m) or (ts_type(m.result) if m.result else "unknown")


def _ts_function(m: Method) -> list[str]:
    doc = [f"   * {line}" if line else "   *" for line in _doc_lines(m, "@param args.")]
    return [
        "  /**",
        *doc,
        "   */",
        f"  function {m.method}({_ts_args(m)}): {_ts_returns(m)};",
    ]


def render_ts(model: ProfileModel) -> str:
    lines = [
        f"// {_marker(model)}",
        f"// {SPDX}",
        f"// The Code Mode namespaces of {model.profile} (ADR-0031): one per broker action prefix,",
        "// holding only the actions the broker admits for this profile.  Each function is one",
        "// broker request for the action it names, its argument the request's params; it returns",
        "// the result, and one that needs a person's approval pauses the run until it is decided.",
        "",
        *_ts_result_types(model),
    ]
    for ns, methods in model.namespaces.items():
        lines.append(f"declare namespace {ns} {{")
        for i, m in enumerate(methods):
            if i:
                lines.append("")
            lines += _ts_function(m)
        lines += ["}", ""]
    return "\n".join(lines).rstrip("\n") + "\n"


# ---------------------------------------------------------------------- Python
def _py_str(text: str) -> str:
    """A double-quoted Python literal of ``text``: printable characters as they are (an astral
    one too, never as a surrogate pair), anything else escaped."""
    out = []
    for c in text:
        if c in '"\\':
            out.append("\\" + c)
        elif c.isprintable():
            out.append(c)
        elif ord(c) < 0x100:
            out.append(f"\\x{ord(c):02x}")
        elif ord(c) < 0x10000:
            out.append(f"\\u{ord(c):04x}")
        else:
            out.append(f"\\U{ord(c):08x}")
    return '"' + "".join(out) + '"'


def _py_literal(value: Any) -> str | None:
    if isinstance(value, bool):
        return "True" if value else "False"
    if value is None:
        return "None"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        return _py_str(value)
    return None  # a float or a structure: typing.Literal cannot hold one


def py_type(schema: Any, used: set[str]) -> str:
    """The Python annotation of a JSON Schema; ``used`` collects the ``typing`` names it needs."""
    if not isinstance(schema, Mapping):
        used.add("Any")
        return "Any"
    values = [schema["const"]] if "const" in schema else schema.get("enum")
    if isinstance(values, list):
        lits = [_py_literal(v) for v in values]
        if values and all(x is not None for x in lits):
            used.add("Literal")
            return f"Literal[{', '.join(dict.fromkeys(lits))}]"
        return py_type({k: v for k, v in schema.items() if k not in ("const", "enum")}, used)
    alts = _alternatives(schema)
    if alts is not None:
        out = _union((py_type(a, used) for a in alts), "Any")
        if out == "Any":
            used.add("Any")
        return out
    t = schema.get("type")
    if t in _PY_TYPES:
        return _PY_TYPES[t]
    if t == "array":
        return f"list[{py_type(schema.get('items', {}), used)}]"
    if t == "object":
        ap = _open_value(schema)
        if not schema.get("properties") and isinstance(ap, Mapping):
            return f"dict[str, {py_type(ap, used)}]"
    used.add("Any")
    return "dict[str, Any]" if t == "object" else "Any"


def _class_name(*parts: str) -> str:
    return "".join(p.capitalize() for part in parts for p in part.split("_") if p)


def _result_name(m: Method) -> str | None:
    """The named type of an action's result: ``LaneWrite`` for every lane action (one shape), else
    ``<Namespace><Method>Result`` for a result object with properties, else ``None``."""
    if not (m.result and m.result.get("type") == "object" and m.result.get("properties")):
        return None
    return "LaneWrite" if m.kind == "lane" else _class_name(m.namespace, m.method) + "Result"


def _result_types(model: ProfileModel) -> dict[str, Mapping[str, Any]]:
    """Name -> result schema, sorted by name; two different schemas under one name are refused."""
    out: dict[str, Mapping[str, Any]] = {}
    for m in model.methods:
        name = _result_name(m)
        if name and out.setdefault(name, m.result) != m.result:
            raise CodemodeError([f"{model.profile}: two result shapes render as {name}"])
    return dict(sorted(out.items()))


def _doc_lines(m: Method, param_prefix: str) -> list[str]:
    """The method's documentation: summary, tier, approval, then one line per parameter."""
    head = f"{m.summary} Tier {m.tier}."
    if m.needs_approval:
        head += " Needs a person's approval: the run pauses until it is decided."
    props = m.params.get("properties") or {}
    params = []
    for name in sorted(props):
        note = _param_note(props[name])
        if note:
            params.append(f"{param_prefix}{name} {note}" if param_prefix else f"{name}: {note}")
    return [head, "", *params] if params else [head]


def _param_note(schema: Any) -> str:
    """A parameter's description, pattern and bounds (each checked one line by the model)."""
    if not isinstance(schema, Mapping):
        return ""
    parts = []
    if isinstance(schema.get("description"), str):
        parts.append(schema["description"])
    if isinstance(schema.get("pattern"), str):
        parts.append(f"matching {schema['pattern']}")
    bounds = [
        f"{label} {schema[key]}"
        for key, label in (
            ("minimum", ">="),
            ("maximum", "<="),
            ("minLength", "length >="),
            ("maxLength", "length <="),
        )
        if isinstance(schema.get(key), int | float) and not isinstance(schema.get(key), bool)
    ]
    if bounds:
        parts.append(", ".join(bounds))
    return "; ".join(parts)


def _py_args(m: Method, used: set[str]) -> list[str]:
    props = m.params.get("properties") or {}
    required = set(m.params.get("required", []))
    args = []
    if props:
        args.append("*")
        args += [
            f"{n}: {py_type(props[n], used)}{'' if n in required else ' = ...'}"
            for n in sorted(props, key=lambda n: (n not in required, n))
        ]
    ap = _open_value(m.params)
    if ap is not False:
        args.append(f"**params: {py_type(ap if isinstance(ap, Mapping) else True, used)}")
    return args


def _py_returns(m: Method, used: set[str]) -> str:
    if _result_name(m):
        return _result_name(m)
    if m.result:
        return py_type(m.result, used)
    used.add("Any")
    return "Any"


def _py_method(m: Method, used: set[str]) -> list[str]:
    args = ["self", *_py_args(m, used)]
    returns = _py_returns(m, used)
    doc = _doc_lines(m, "")
    body = [f'        r"""{doc[0]}'] + [f"        {d}" if d else "" for d in doc[1:]]
    body = [*body, '        """'] if len(doc) > 1 else [body[0] + '"""']
    return [*_py_signature(m.method, args, returns), *body]


def _py_signature(name: str, args: list[str], returns: str) -> list[str]:
    """``def`` wrapped the way ``ruff format`` wraps it at 100 columns, so the committed stubs
    pass ``make lint`` as written."""
    one = f"    def {name}({', '.join(args)}) -> {returns}:"
    if len(one) <= LINE_LENGTH:
        return [one]
    hugged = f"        {', '.join(args)}"
    if len(hugged) <= LINE_LENGTH:
        return [f"    def {name}(", hugged, f"    ) -> {returns}:"]
    return [f"    def {name}(", *(f"        {a}," for a in args), f"    ) -> {returns}:"]


def render_py(model: ProfileModel) -> str:
    used: set[str] = set()
    blocks: list[list[str]] = []
    for name, schema in _result_types(model).items():
        props, req = schema["properties"], set(schema.get("required", []))
        fields = []
        for n in sorted(props):
            t = py_type(props[n], used)
            if n not in req:
                used.add("NotRequired")
                t = f"NotRequired[{t}]"
            fields.append(f"    {n}: {t}")
        used.add("TypedDict")
        blocks.append([f"class {name}(TypedDict):", *fields])
    bindings = []
    for ns, methods in model.namespaces.items():
        cls = "_" + _class_name(ns)
        block = [f"class {cls}:"]
        for i, m in enumerate(methods):
            if i:
                block.append("")
            block += _py_method(m, used)
        blocks.append(block)
        bindings.append(f"{ns}: {cls}")
    head = [
        f"# {_marker(model)}",
        f"# {SPDX}",
        f'"""The Code Mode namespaces of {model.profile} (ADR-0031): one per broker action prefix,',
        "holding only the actions the broker admits for this profile.  Each method is one broker",
        "request for the action it names, its keyword arguments the request's params; it returns the",
        "result, and one that needs a person's approval pauses the run until it is decided.",
        '"""',
        "",
    ]
    if used:
        head += [f"from typing import {', '.join(sorted(used))}", ""]
    if not blocks:
        return "\n".join(head)
    body = "\n\n".join("\n".join(b) for b in blocks)
    return "\n".join(head) + "\n" + body + "\n\n" + "\n".join(bindings) + "\n"


# ------------------------------------------------------------------ the index
def _signatures(m: Method) -> dict[str, str]:
    used: set[str] = set()
    py_args = ", ".join(_py_args(m, used))
    call = f"{m.namespace}.{m.method}"
    return {
        "python": f"{call}({py_args}) -> {_py_returns(m, used)}",
        "typescript": f"{call}({_ts_args(m)}): {_ts_returns(m)}",
    }


def render_index(model: ProfileModel) -> str:
    doc = {
        "_generated": _marker(model),
        "profile": model.profile,
        "actions": [
            {
                "name": m.action,
                "call": f"{m.namespace}.{m.method}",
                "summary": m.summary,
                "tier": m.tier,
                "needs_approval": m.needs_approval,
                "kind": m.kind,
                "params": m.params,
                "result": (
                    {"type": _result_name(m) or ts_type(m.result), "schema": m.result}
                    if m.result
                    else None
                ),
                "signatures": _signatures(m),
            }
            for m in model.methods
        ],
    }
    # ASCII only: the index is data, and an escape cannot hide a bidi or zero-width character
    return json.dumps(doc, indent=2, sort_keys=True) + "\n"


# ------------------------------------------------------------------- the tree
def _check_names(model: ProfileModel) -> None:
    """Two namespaces whose classes would share a name, or two result shapes one type name, are
    refused."""
    owners: dict[str, str] = {}
    problems = []
    for ns in model.namespaces:
        cls = "_" + _class_name(ns)
        if owners.setdefault(cls, ns) != ns:
            problems.append(
                f"{model.profile}: namespaces {ns} and {owners[cls]} both render as {cls}"
            )
    if problems:
        raise CodemodeError(problems)
    _result_types(model)


def render_files(models: Iterable[ProfileModel]) -> dict[str, str]:
    """``<slug>/<file>`` -> text for every model, sorted."""
    out: dict[str, str] = {}
    for model in models:
        _check_names(model)
        out[f"{model.slug}/search.json"] = render_index(model)
        out[f"{model.slug}/stubs.pyi"] = render_py(model)
        out[f"{model.slug}/types.d.ts"] = render_ts(model)
    return dict(sorted(out.items()))


def render(manifest: str | Path) -> dict[str, str]:
    """Load and validate the broker manifest at ``manifest`` and render every profile.  Raises
    :class:`homelabnext.broker.service.ManifestError` or :class:`CodemodeError`."""
    from homelabnext.broker.service import load_manifest

    doc, handler_docs = load_manifest(manifest)
    return render_files(build_models(doc, handler_docs))


def _is_ours(path: Path) -> bool:
    """``path`` is a regular file (not a symlink) whose first two lines carry the marker (the
    second for ``search.json``, after its opening brace)."""
    try:
        if not stat.S_ISREG(os.lstat(path).st_mode):
            return False
        fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW)
    except OSError:
        return False
    with os.fdopen(fd, "rb") as fh:
        head = fh.read(1024).decode("utf-8", errors="replace").split("\n")[:2]
    return any(GENERATOR in line for line in head)


def _marked(out: Path) -> list[str]:
    """The ``<slug>/<file>`` under ``out`` this generator wrote: only a real (not symlinked)
    profile directory, only the names in :data:`FILES`, and only a marked regular file."""
    if not out.is_dir():
        return []
    found = []
    for d in sorted(out.iterdir()):
        if not SLUG_RE.fullmatch(d.name) or not stat.S_ISDIR(os.lstat(d).st_mode):
            continue
        found += [f"{d.name}/{n}" for n in FILES if _is_ours(d / n)]
    return found


def check(out: str | Path, files: Mapping[str, str]) -> list[str]:
    """Drift between ``files`` and ``out`` (empty = clean): missing, differing, symlinked and
    stale files.  An unreadable file raises ``OSError`` (the check could not measure)."""
    out = Path(out)
    problems = []
    for rel, text in files.items():
        p = out / rel
        if p.parent.is_symlink() or p.is_symlink():
            problems.append(f"symlink: {rel}")
        elif not p.is_file():
            problems.append(f"missing: {rel}")
        elif p.read_bytes() != text.encode("utf-8"):
            problems.append(f"differs: {rel}")
    problems += [f"stale: {rel}" for rel in _marked(out) if rel not in files]
    return problems


def _destinations(out: Path, files: Mapping[str, str]) -> list[str]:
    """Every reason a write of ``files`` into ``out`` would leave ``out`` (empty = safe)."""
    root = out.resolve()
    problems = []
    for rel in files:
        d, dest = out / rel.split("/")[0], out / rel
        if d.is_symlink() or (d.exists() and not d.is_dir()):
            problems.append(f"{d.name}: is a symlink or not a directory")
        elif d.exists() and d.resolve().parent != root:
            problems.append(f"{d.name}: resolves outside {out}")
        elif dest.is_symlink() or (dest.exists() and not dest.is_file()):
            problems.append(f"{rel}: is a symlink or not a regular file")
    return sorted(set(problems))


def _replace(dest: Path, data: bytes) -> None:
    # a fresh name created exclusively ("x" refuses any existing path, a symlink included) with
    # the mode the umask gives every other file in the checkout; mkstemp's 0600 would leave the
    # goldens unreadable to other users, and a fixed chmod would override the umask
    tmp = dest.parent / f".{dest.name}.{secrets.token_hex(8)}.tmp"
    try:
        with open(tmp, "xb") as fh:
            fh.write(data)
        os.replace(tmp, dest)
    except BaseException:
        with contextlib.suppress(OSError):
            os.unlink(tmp)
        raise


def write(out: str | Path, files: Mapping[str, str]) -> tuple[list[str], list[str], list[str]]:
    """Write ``files`` under ``out``; delete this generator's files it no longer renders.
    Returns (written, unchanged, removed).  Refuses (:class:`CodemodeError`, nothing written) a
    destination that is a symlink or resolves outside ``out``."""
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    problems = _destinations(out, files)
    if problems:
        raise CodemodeError(problems)
    written, unchanged = [], []
    for rel, text in files.items():
        dest, data = out / rel, text.encode("utf-8")
        dest.parent.mkdir(exist_ok=True)
        if dest.is_file() and dest.read_bytes() == data:
            unchanged.append(rel)
            continue
        _replace(dest, data)
        written.append(rel)
    removed = []
    for rel in _marked(out):
        if rel in files or not _is_ours(out / rel):  # checked again just before the unlink
            continue
        (out / rel).unlink()
        removed.append(rel)
        with contextlib.suppress(OSError):
            (out / rel).parent.rmdir()  # only when empty
    return written, unchanged, removed
