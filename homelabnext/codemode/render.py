"""Render a profile's :class:`~.model.ProfileModel` as the three Code Mode files.

``<out>/<profile slug>/`` gets, from the same model:

* ``types.d.ts`` -- TypeScript: one ``declare namespace`` per action prefix, one function per
  action taking the action's params as one object;
* ``stubs.pyi``  -- Python: one class per namespace (``_Service``) bound to a module-level name
  (``service``), one method per action taking the params as keyword-only arguments;
* ``search.json`` -- the index ``codemode_search`` and ``codemode_describe`` read: per action its
  ``name``, the ``call`` a program writes, ``summary``, ``tier``, ``needs_approval``, ``kind``,
  ``params`` (the JSON Schema), ``result`` (its type name and schema, or null) and
  ``signatures`` (one line per language).

Calls are **synchronous** in both languages: a call returns its result, and a call that needs a
person's approval pauses the whole run until it is decided (ADR-0031 decision 7).

Types come from the JSON Schema of the params: ``string``, ``integer``/``number``, ``boolean``,
``null``, ``array`` of ``items``, ``enum``/``const`` as literals, ``oneOf``/``anyOf`` and a type
list as unions, a property absent from ``required`` as optional, and ``additionalProperties``
as the value type of an open object (``Record<string, T>``, ``dict[str, T]``, ``**params: T``).
A result with properties is a named type (``LaneWrite`` for every lane action, else
``<Namespace><Method>Result``: an interface and a ``TypedDict``); an action without a result
schema returns ``unknown``/``Any``.  Where a stub is wider than the schema, it is so on
purpose, and the index's ``params`` keeps the exact schema:

* a nested object with ``properties`` is an inline object type in TypeScript but
  ``dict[str, Any]`` in Python (no nested ``TypedDict``);
* an object with both ``properties`` and a typed ``additionalProperties`` gets an ``unknown``
  index signature in TypeScript (each property's type would have to fit it);
* ``allOf``, ``$ref``, ``not``, ``if``/``then`` and anything else not listed above are
  ``unknown``/``Any``; ``pattern``, bounds and lengths are not types (the parameter notes name
  them);
* a float ``enum`` or ``const`` is ``float`` in Python, which ``Literal`` cannot hold.

Every file starts with the marker line (``generated by hnx codemode gen ... do not edit``, with
the model's digest) that ADR-0028's backstop test reads.  ``--check`` compares every file byte for
byte and reports as stale a marked ``<out>/<slug>/<one of FILES>`` that is no longer rendered (a
profile whose grant was removed), which a write deletes.  Nothing else under ``<out>`` is ever
touched: a symlinked profile directory or file is refused, every file is written through a
temporary file and ``os.replace`` in its own directory, and a stale file is checked again (a
regular file, still marked) just before it is unlinked.
"""

