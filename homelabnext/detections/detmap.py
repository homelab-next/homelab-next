"""Logical ``det:<slug>`` <-> engine rule number map (generated, never hand-edited).

Engine numbers live ONLY here. Charters, profiles, decision specs and
schedules reference ``det:<slug>``; the lint in ``lint.py`` enforces it.
Existing assignments are stable; numbers of removed rules are retired, never reused.
"""

from __future__ import annotations

from pathlib import Path

import yaml

from .sigma import Rule

SCHEMA_ID = "homelabnext.detections.det_map/v1"
DEFAULT_BASE = 900001  # synthetic example range; real deployments choose their own


class DetMapError(ValueError):
    pass


def generate(rules: list[Rule], existing: dict | None = None, base: int = DEFAULT_BASE) -> dict:
    existing = existing or {}
    entries: dict[str, int] = dict(existing.get("entries", {}))
    retired: list[int] = list(existing.get("retired", []))
    live = {r.det_id for r in rules}
    for det in sorted(set(entries) - live):
        retired.append(entries.pop(det))
    used = set(entries.values()) | set(retired)
    nxt = max(used | {base - 1}) + 1
    for r in sorted(rules, key=lambda r: r.slug):
        if r.det_id not in entries:
            entries[r.det_id] = nxt
            used.add(nxt)
            nxt += 1
    if len(set(entries.values())) != len(entries):
        raise DetMapError("duplicate engine numbers in map")
    return {
        "schema": SCHEMA_ID,
        "engine_numbers_live_here_only": True,
        "entries": dict(sorted(entries.items())),
        "retired": sorted(set(retired)),
    }


def dump(m: dict) -> str:
    return (
        "# SPDX-License-Identifier: Apache-2.0\n"
        "# GENERATED by `python -m homelabnext.detections map`. Do not edit by hand.\n"
        + yaml.safe_dump(m, sort_keys=False)
    )


def load(path: Path) -> dict:
    m = yaml.safe_load(Path(path).read_text(encoding="utf-8")) or {}
    if m.get("schema") != SCHEMA_ID:
        raise DetMapError(f"{path}: schema must be {SCHEMA_ID}")
    return m


def reverse(m: dict) -> dict[int, str]:
    return {v: k for k, v in m["entries"].items()}


def check_current(rules: list[Rule], m: dict) -> list[str]:
    """Problems if the stored map is not exactly what the generator would keep.

    Besides the key sets, the numbers themselves: every entry is an int, no two entries share
    one, no live entry reuses a retired one, and regenerating from the stored map changes
    nothing. A hand edit that duplicates or reuses a number fails here, not only on ``map``.
    """
    problems = []
    entries = m.get("entries") or {}
    retired = list(m.get("retired") or [])
    live = {r.det_id for r in rules}
    for det in sorted(live - set(entries)):
        problems.append(f"{det}: no engine number in det map (regenerate)")
    for det in sorted(set(entries) - live):
        problems.append(f"{det}: in det map but no rule exists (regenerate to retire it)")
    bad = sorted(d for d, n in entries.items() if type(n) is not int)
    bad += [f"retired {n!r}" for n in retired if type(n) is not int]
    for d in bad:
        problems.append(f"{d}: engine number is not an integer")
    by_num: dict[object, list[str]] = {}
    for det, n in entries.items():
        by_num.setdefault(n, []).append(det)
    for n, dets in sorted(by_num.items(), key=lambda kv: str(kv[0])):
        if len(dets) > 1:
            problems.append(f"engine number {n} is assigned to {', '.join(sorted(dets))}")
    for det, n in sorted(entries.items()):
        if n in retired:
            problems.append(f"{det}: engine number {n} is retired and must never be reused")
    if len(retired) != len(set(map(str, retired))):
        problems.append("retired: a number is listed more than once")
    if not problems:
        regen = generate(rules, m)
        if any(regen[k] != m.get(k) for k in regen):
            problems.append("det map is not what the generator would write (regenerate)")
    return problems
