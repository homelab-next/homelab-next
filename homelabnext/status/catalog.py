"""The generated source catalog, ``docs/status/sources.md``: every registered status source --
what it reports, its kind, target, interval and staleness -- so the menu users pick views from is
readable without the registry open.  ``hnx status catalog check`` (``make gates``) fails when the
page differs from what the registry generates, like the capability pages.
"""

from __future__ import annotations

from collections.abc import Sequence
from pathlib import Path

from homelabnext.context.levels import generated_summary_lines

from .model import SourceSpec

PAGE = Path("docs/status/sources.md")
GENERATOR = "hnx status catalog generate"
SUMMARY = (
    "The status hub menu: every status source a service offers, with its module, kind, "
    "interval, stale-after window and what it reports."
)
#: the example lab whose UPS sources (generated from its site model) the page also lists
POWER_LAB = "examples/lab-topology"


def power_lab(directory: str | Path) -> list[SourceSpec]:
    """The sources :mod:`.power` generates for a lab directory (``services.yml``, ``site.yml``,
    ``guests/``): only those with a site UPS behind them."""
    from homelabnext.registry.model import load

    from .model import sources_from_registry
    from .power import load as load_power

    d = Path(directory)
    specs = sources_from_registry(load(d / "services.yml"))
    guests = d / "guests"
    out = load_power(specs, d / "site.yml", guests if guests.is_dir() else None)
    return [s for s in out if s.power is not None]


def _dur(seconds: float) -> str:
    s = int(seconds)
    for unit, n in (("d", 86400), ("h", 3600), ("min", 60)):
        if s >= n and s % n == 0:
            return f"{s // n} {unit}"
    return f"{s} s"


def _target(d: dict) -> str:
    t = d["target"]
    if "file" in t:
        return f"file `{t['file']}`"
    if "service" in t and "path" not in t:
        return f"`{t['service']}` (upsd, NUT protocol)"
    if "service" in t:
        return f"`{t['service']}` `{t['path']}`"
    return "pushed (`homelabnext.status.observed`)"


def _credential(s: SourceSpec) -> str:
    if not s.auth:
        return ""
    if s.kind == "poll-nut":
        tls = "STARTTLS" if s.mapping.get("tls", "starttls") == "starttls" else "no TLS"
        return (
            f"- Credential: NUT `USERNAME {s.auth.get('username')}`, `PASSWORD` from the secret "
            f"store (this source's `auth.secret`), over {tls}\n"
        )
    header = f"`{s.auth['header']}`" if s.auth.get("header") else "`Authorization: Bearer`"
    # the page says where the credential is configured, never anything read for the secret store
    return f"- Credential: from the secret store (this source's `auth.secret`), sent as {header}\n"


def _section(s: SourceSpec, *, linked: bool = True) -> str:
    d = s.describe()
    declared = (
        f"[`svc:{d['service']}`](../systems/{d['service']}.md) "
        f"([[systems/{d['service']}|{d['service']}]])"
        if linked
        else f"`svc:{d['service']}` of `{POWER_LAB}/services.yml`"
    )
    feeds = ""
    if s.power is not None:
        devices = ", ".join(f"`{x}`" for x in s.power["devices"]) or "none"
        guests = ", ".join(f"`{x}`" for x in s.power["guests"]) or "none"
        feeds = f"- Site UPS `{s.power['ups']}`; feeds {devices}; guests on it: {guests}\n"
    return (
        f"### {d['id']}\n\n{d['what']}\n\n"
        f"- Declared by: {declared}, capability `cap:{d['capability']}`\n"
        f"- Kind: `{d['kind']}`; target: {_target(d)}\n"
        f"- Mapping: {d['mapping']}\n"
        + _credential(s)
        + feeds
        + f"- Module: `{d['module']}`; graph node `status:{d['id']}`\n"
        f"- Every {_dur(d['interval_s'])}, timeout {_dur(d['timeout_s'])}; stale after "
        f"{_dur(d['stale_after_s'])} without a reading; a failed poll reads as "
        f"`{d['on_error']}`\n"
    )


def _power_part(ups: Sequence[SourceSpec]) -> str:
    if not ups:
        return ""
    rows = "\n".join(
        f"| [`{s.id}`](#{s.id}) | `{s.power['ups']}` | {len(s.power['devices'])} "
        f"| {len(s.power['guests'])} | {s.what} |"
        for s in ups
        if s.power is not None
    )
    return (
        "\n## UPS sources generated from a site model\n\n"
        f"> Generated by `hnx status catalog generate` from `{POWER_LAB}` (its `services.yml`, "
        "`site.yml` and `guests/`): a `poll-nut` source without `mapping.ups` is a template, "
        "expanded into one source per site UPS with `monitored_by: nut` and a `nut_name` "
        "([status hub](../status.md#8-ups-power-network-ups-tools)). Run the hub with the same "
        "`--site` to get them.\n\n"
        "| Source | UPS | Devices fed | Guests on it | What it reports |\n"
        "|---|---|---|---|---|\n"
        + rows
        + "\n\n"
        + "\n".join(_section(s, linked=False) for s in ups)
    )


def render_catalog(specs: Sequence[SourceSpec], ups: Sequence[SourceSpec] = ()) -> str:
    rows = []
    sections = []
    for s in specs:
        d = s.describe()
        kind = d["kind"] + (" (reserved: stage 2)" if d["reserved"] else "")
        rows.append(
            f"| [`{d['id']}`](#{d['id']}) | {d['module']} | {kind} | {_dur(d['interval_s'])} "
            f"| {_dur(d['stale_after_s'])} | {d['what']} |"
        )
        sections.append(_section(s))
    return (
        "---\ntitle: Status sources\ntype: status-catalog\n"
        f"{generated_summary_lines(SUMMARY)}\n"
        f"generated_by: {GENERATOR}\n---\n\n"
        "# Status sources\n\n"
        f"> Generated by `{GENERATOR}` from the `status_sources` of `examples/services.yml`. "
        "Do not edit: change the registry and regenerate.\n\n"
        "The menu of the status hub ([status hub](../status.md) ([[status]]), "
        "[ADR-0013](../adr/0013-status-hub.md)): every source a service offers, by registry "
        "name. Views (`examples/status/views.yml`) pick from this list. A source that reports "
        "nothing for its staleness window reads as `stale`.\n\n"
        "| Source | Module | Kind | Interval | Stale after | What it reports |\n"
        "|---|---|---|---|---|---|\n"
        + "\n".join(rows)
        + "\n\n## Sources\n\n"
        + "\n".join(sections)
        + _power_part(ups)
        + "\n## Regenerate and check\n\n"
        "```\nhnx status catalog generate   # rewrite this page from the registry\n"
        "hnx status catalog check      # exit 1 when it is stale (make gates, CI)\n```\n"
    )


def generate(path: str | Path, specs: Sequence[SourceSpec], ups: Sequence[SourceSpec] = ()) -> Path:
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(render_catalog(specs, ups), encoding="utf-8")
    return p


def check(
    path: str | Path, specs: Sequence[SourceSpec], ups: Sequence[SourceSpec] = ()
) -> list[str]:
    """Problems (empty = current)."""
    p = Path(path)
    try:
        text = p.read_text(encoding="utf-8")
    except OSError:
        return [f"{p}: missing (run `{GENERATOR}`)"]
    if text != render_catalog(specs, ups):
        return [f"{p}: stale (run `{GENERATOR}`)"]
    return []
