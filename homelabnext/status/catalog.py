"""The generated source catalog, ``docs/status/sources.md``: every registered status source --
what it reports, its kind, target, interval and staleness -- so the menu users pick views from is
readable without the registry open.  ``hnx status catalog check`` (``make gates``) fails when the
page differs from what the registry generates, like the capability pages.
"""

from __future__ import annotations

from collections.abc import Sequence
from pathlib import Path

from .model import SourceSpec

PAGE = Path("docs/status/sources.md")
GENERATOR = "hnx status catalog generate"


def _dur(seconds: float) -> str:
    s = int(seconds)
    for unit, n in (("d", 86400), ("h", 3600), ("min", 60)):
        if s >= n and s % n == 0:
            return f"{s // n} {unit}"
    return f"{s} s"


def _target(d: dict) -> str:
    t = d["target"]
    if "file" in t:
        return f"file `{t['file']}`"
    if "service" in t:
        return f"`{t['service']}` `{t['path']}`"
    return "pushed (`homelabnext.status.observed`)"


def _credential(s: SourceSpec) -> str:
    if not s.auth:
        return ""
    header = f"`{s.auth['header']}`" if s.auth.get("header") else "`Authorization: Bearer`"
    return f"- Credential: `{s.auth['secret']}` (a secret-store name) sent as {header}\n"


def render_catalog(specs: Sequence[SourceSpec]) -> str:
    rows = []
    sections = []
    for s in specs:
        d = s.describe()
        kind = d["kind"] + (" (reserved: stage 2)" if d["reserved"] else "")
        rows.append(
            f"| [`{d['id']}`](#{d['id']}) | {d['module']} | {kind} | {_dur(d['interval_s'])} "
            f"| {_dur(d['stale_after_s'])} | {d['what']} |"
        )
        sections.append(
            f"### {d['id']}\n\n{d['what']}\n\n"
            f"- Declared by: [`svc:{d['service']}`](../systems/{d['service']}.md) "
            f"([[systems/{d['service']}|{d['service']}]]), capability `cap:{d['capability']}`\n"
            f"- Kind: `{d['kind']}`; target: {_target(d)}\n"
            f"- Mapping: {d['mapping']}\n"
            + _credential(s)
            + f"- Module: `{d['module']}`; graph node `status:{d['id']}`\n"
            f"- Every {_dur(d['interval_s'])}, timeout {_dur(d['timeout_s'])}; stale after "
            f"{_dur(d['stale_after_s'])} without a reading; a failed poll reads as "
            f"`{d['on_error']}`\n"
        )
    return (
        "---\ntitle: Status sources\ntype: status-catalog\n"
        f"generated_by: {GENERATOR}\n---\n\n"
        "# Status sources\n\n"
        f"> Generated by `{GENERATOR}` from the `status_sources` of `examples/services.yml`. "
        "Do not edit: change the registry and regenerate.\n\n"
        "The menu of the status hub ([status hub](../status.md) ([[status]]), "
        "[ADR-0013](../adr/0013-status-hub.md)): every source a service offers, by registry "
        "name. Views (`examples/status/views.yml`) pick from this list. A source that reports "
        "nothing for its staleness window reads as `stale`.\n\n"
        "| Source | Module | Kind | Interval | Stale after | What it reports |\n"
        "|---|---|---|---|---|---|\n"
        + "\n".join(rows)
        + "\n\n## Sources\n\n"
        + "\n".join(sections)
        + "\n## Regenerate and check\n\n"
        "```\nhnx status catalog generate   # rewrite this page from the registry\n"
        "hnx status catalog check      # exit 1 when it is stale (make gates, CI)\n```\n"
    )


def generate(path: str | Path, specs: Sequence[SourceSpec]) -> Path:
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(render_catalog(specs), encoding="utf-8")
    return p


def check(path: str | Path, specs: Sequence[SourceSpec]) -> list[str]:
    """Problems (empty = current)."""
    p = Path(path)
    try:
        text = p.read_text(encoding="utf-8")
    except OSError:
        return [f"{p}: missing (run `{GENERATOR}`)"]
    if text != render_catalog(specs):
        return [f"{p}: stale (run `{GENERATOR}`)"]
    return []
