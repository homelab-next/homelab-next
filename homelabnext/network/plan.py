"""``plan``: what would change if the rendered files replaced the current ones.

The comparison is between a rendered file set and a directory tree (the "current" state: a
checkout of the last applied render, or a snapshot pulled from a device).  The output is a
terraform-style summary followed by unified diffs.  For JSON documents shaped
``{"objects": [{"name": ...}]}`` (the UniFi payloads) the summary also lists objects by name, so
a reviewer sees ``~ hnx-edge`` rather than a wall of line noise.
"""

from __future__ import annotations

import difflib
import json
from dataclasses import dataclass, field
from pathlib import Path

GENERATED_MARKERS = ("Generated by `hnx site render", '"dry_run": true')


@dataclass(frozen=True)
class ObjectChange:
    key: str
    action: str  # create | update | delete


@dataclass(frozen=True)
class Change:
    path: str
    action: str  # create | update | delete | unchanged
    diff: str = ""
    objects: tuple[ObjectChange, ...] = ()


@dataclass
class Plan:
    adapter: str
    changes: list[Change] = field(default_factory=list)

    @property
    def changed(self) -> bool:
        return any(c.action != "unchanged" for c in self.changes)

    def counts(self) -> dict[str, int]:
        out = {"create": 0, "update": 0, "delete": 0, "unchanged": 0}
        for c in self.changes:
            out[c.action] += 1
        return out

    def to_dict(self) -> dict:
        return {
            "adapter": self.adapter,
            "changed": self.changed,
            "counts": self.counts(),
            "changes": [
                {
                    "path": c.path,
                    "action": c.action,
                    "objects": [{"key": o.key, "action": o.action} for o in c.objects],
                }
                for c in self.changes
            ],
        }

    def render(self, *, diffs: bool = True) -> str:
        n = self.counts()
        lines = [
            f"plan ({self.adapter}): {n['create']} to create, {n['update']} to update, "
            f"{n['delete']} to delete, {n['unchanged']} unchanged"
        ]
        sign = {"create": "+", "update": "~", "delete": "-"}
        for c in self.changes:
            if c.action == "unchanged":
                continue
            lines.append(f"{sign[c.action]} {c.action} {c.path}")
            lines.extend(f"    {sign[o.action]} {o.key}" for o in c.objects)
        if diffs and self.changed:
            lines.append("")
            lines.extend(c.diff.rstrip("\n") for c in self.changes if c.diff)
        return "\n".join(lines) + "\n"


def _objects(text: str) -> dict[str, str] | None:
    try:
        doc = json.loads(text)
    except ValueError:
        return None
    objs = doc.get("objects") if isinstance(doc, dict) else None
    if not isinstance(objs, list) or not all(isinstance(o, dict) and "name" in o for o in objs):
        return None
    return {o["name"]: json.dumps(o, sort_keys=True) for o in objs}


def _object_changes(old: str, new: str) -> tuple[ObjectChange, ...]:
    a, b = _objects(old), _objects(new)
    if a is None or b is None:
        return ()
    out = [ObjectChange(k, "create") for k in b if k not in a]
    out += [ObjectChange(k, "update") for k in b if k in a and a[k] != b[k]]
    out += [ObjectChange(k, "delete") for k in a if k not in b]
    return tuple(out)


def _udiff(path: str, old: str, new: str) -> str:
    return "".join(
        difflib.unified_diff(
            old.splitlines(keepends=True),
            new.splitlines(keepends=True),
            fromfile=f"current/{path}",
            tofile=f"desired/{path}",
        )
    )


def read_tree(root: Path | None) -> dict[str, str]:
    """All text files under ``root`` as posix-relative path -> content."""
    if root is None or not root.is_dir():
        return {}
    out = {}
    for p in sorted(root.rglob("*")):
        if p.is_file() and not p.is_symlink():
            try:
                out[p.relative_to(root).as_posix()] = p.read_text(encoding="utf-8")
            except UnicodeDecodeError:
                continue
    return out


def is_generated(text: str) -> bool:
    head = text[:400]
    return any(m in head for m in GENERATED_MARKERS)


def compute_plan(adapter: str, rendered: dict[str, str], current: Path | None) -> Plan:
    have = read_tree(current)
    plan = Plan(adapter)
    for path in sorted(set(rendered) | {p for p, t in have.items() if is_generated(t)}):
        new = rendered.get(path)
        old = have.get(path)
        if new is not None and old is None:
            plan.changes.append(
                Change(path, "create", _udiff(path, "", new), _object_changes("{}", new))
            )
        elif new is None and old is not None:
            plan.changes.append(
                Change(path, "delete", _udiff(path, old, ""), _object_changes(old, "{}"))
            )
        elif new == old:
            plan.changes.append(Change(path, "unchanged"))
        else:
            plan.changes.append(
                Change(
                    path, "update", _udiff(path, old or "", new or ""), _object_changes(old, new)
                )
            )
    return plan


def write_rendered(rendered: dict[str, str], out: Path, *, prune: bool = False) -> list[str]:
    """Write files that differ; return the paths touched.  A second call returns ``[]``."""
    touched: list[str] = []
    have = read_tree(out)
    for path, text in sorted(rendered.items()):
        if have.get(path) == text:
            continue
        target = out / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
        touched.append(path)
    if prune:
        for path, text in sorted(have.items()):
            if path not in rendered and is_generated(text):
                (out / path).unlink()
                touched.append(path)
    return touched
