"""The adapter interface.

An adapter turns the vendor-neutral :class:`~homelabnext.network.ir.NetworkIR` into files.
``render`` is pure and deterministic: same IR, same bytes.  ``apply`` (touching a live device) is
SERVER-only and not implemented by any adapter in this repository.
"""

from __future__ import annotations

from typing import ClassVar

from ..ir import NetworkIR

Rendered = dict[str, str]  # relative path (posix) -> file content


class AdapterError(Exception):
    """Base class for adapter registry and rendering failures."""


class UnknownAdapter(AdapterError):
    def __init__(self, name: str, known: list[str]):
        self.name = name
        self.known = known
        super().__init__(f"unknown adapter {name!r}; known adapters: {', '.join(known)}")


class AdapterDeferred(AdapterError):
    def __init__(self, name: str, reason: str):
        self.name = name
        super().__init__(f"adapter {name!r} is deferred: {reason}")


class ServerOnly(AdapterError):
    """Raised by ``apply``: live application needs the real device and its credentials."""


class Adapter:
    name: ClassVar[str]
    status: ClassVar[str] = "ready"  # ready | deferred
    summary: ClassVar[str] = ""

    def render(self, ir: NetworkIR) -> Rendered:  # pragma: no cover - interface
        raise NotImplementedError

    def apply(self, ir: NetworkIR) -> None:
        raise ServerOnly(
            f"adapter {self.name!r}: applying to a live device is SERVER-only; "
            "use `hnx site plan` to review what would change"
        )


def header(adapter: str, comment: str = "#") -> str:
    return f"{comment} Generated by `hnx site render --adapter {adapter}`; do not edit by hand.\n"
