"""Tiny deterministic text helpers (JSON strings are valid YAML literals; :func:`hq` makes them HCL)."""

from __future__ import annotations

import json
from typing import Any

HEADER = "generated by hnx guests render; do not edit"


def q(value: Any) -> str:
    """Quote a scalar: JSON encoding, which is a valid YAML flow scalar and HCL literal."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if value is None:
        return "null"
    if isinstance(value, int | float):
        return str(value)
    return json.dumps(str(value), ensure_ascii=True)


def qlist(values: list[Any]) -> str:
    return "[" + ", ".join(q(v) for v in values) + "]"


def hq(value: Any) -> str:
    """Quote a scalar as an HCL string literal.

    A JSON string is an HCL literal except for template sequences: HCL interpolates ``${...}``
    and evaluates ``%{...}`` directives inside quoted strings, so those are escaped to ``$${``
    and ``%%{`` (the literal forms).  Use :func:`q` for YAML, where the doubling would change
    the value.
    """
    text = q(value)
    if isinstance(value, str):
        text = text.replace("${", "$${").replace("%{", "%%{")
    return text


def hqlist(values: list[Any]) -> str:
    return "[" + ", ".join(hq(v) for v in values) + "]"


def tf_ident(name: str) -> str:
    return name.replace("-", "_")


def hcl_align(text: str) -> str:
    """Align ``=`` across runs of consecutive attribute lines at one indent (terraform fmt style)."""
    import re

    attr = re.compile(r"^(\s*)([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$")
    lines = text.split("\n")
    out: list[str] = []
    i = 0
    while i < len(lines):
        m = attr.match(lines[i])
        if not m:
            out.append(lines[i])
            i += 1
            continue
        run = [m]
        j = i + 1
        while j < len(lines):
            n = attr.match(lines[j])
            if not n or n.group(1) != m.group(1):
                break
            run.append(n)
            j += 1
        width = max(len(r.group(2)) for r in run)
        out += [f"{r.group(1)}{r.group(2).ljust(width)} = {r.group(3)}" for r in run]
        i = j
    return "\n".join(out)
