def schedule_id(tid: str) -> str:
    return f"cti-{tid}"


def pack_name(tid: str) -> str:
    return PREFIX + tid


def rule_id(index: int) -> str:
    return f"C{index + 1:02d}"


def render_pack(timer: tuple, lane: str = LANE) -> str:
    rid = rule_id(TIMERS.index(timer)).lower()
    tid, cron, agent, priority, _window, old = timer
    if lane not in LANES:
        raise ValueError(f"lane is one of {LANES}")
    sid = schedule_id(tid)
    shadow = "      shadow: true\n" if lane == "shadow" else ""
    return f"""# SPDX-License-Identifier: Apache-2.0
# Generated by homelabnext.workflows.cti_schedules; edit the table there, not this file.
# {sid}: queue one {agent} job on the orchestration controller at `{cron}` (UTC),
# the lane the table was rendered for ({lane}).  Replaces the old timer {old}.  The firing's
# event id (the schedule and the firing time) is the idempotency key, so a timer that fires twice
# is one job.  The pack never runs the job: the controller admits it against live load.
pack: {pack_name(tid)}
version: 1
description: Queue one {agent} job for the {sid} schedule ({cron} UTC, lane {lane}).
trigger:
  event: homelabnext.schedule.fired
  where:
    - {{ref: $event.data.schedule, equals: {sid}}}
actor: profile:workflow-agents
broker_manifest: workflows/broker.manifest.json
steps:
  - id: submit
    kind: action
    action: agent.job.submit
    target: svc:orchestrator
    params:
      agent_key: {agent}
      idempotency_key: $event.id
      priority: {priority}
{shadow}      task_description: "{sid}: scheduled run, {cron} UTC, lane {lane}"
fixtures:
  - name: {sid}-fired-queues-one-job
    event:
      specversion: "1.0"
      id: evt-{rid}-1
      source: svc:automation
      type: homelabnext.schedule.fired
      time: "2026-01-01T00:00:00Z"
      data: {{schedule: {sid}, fired_at: "2026-01-01T00:00:00Z", cron: "{cron}"}}
    expect:
      calls:
        - action: agent.job.submit
          target: svc:orchestrator
          params:
            agent_key: {agent}
            idempotency_key: evt-{rid}-1
            priority: {priority}
{shadow.replace("      ", "            ", 1) if shadow else ""}            task_description: "{sid}: scheduled run, {cron} UTC, lane {lane}"
          result: executed
  - name: another-schedule-ignored
    event:
      specversion: "1.0"
      id: evt-{rid}-2
      source: svc:automation
      type: homelabnext.schedule.fired
      time: "2026-01-01T00:00:00Z"
      data: {{schedule: not-{sid}, fired_at: "2026-01-01T00:00:00Z"}}
    expect:
      triggered: false
      calls: []
"""


def render_rules() -> str:
    out = [BEGIN]
    for i, (tid, cron, _a, _p, window, old) in enumerate(TIMERS):
        out.append(f"  # {rule_id(i)}: replaces {old}")
        out.append(f"  - pack: {pack_name(tid)}")
        out.append(f"    id: {rule_id(i)}")
        out.append("    mode: shadow")
        out.append(f'    schedule: {{id: {schedule_id(tid)}, cron: "{cron}"}}')
        out.append(f"    coalesce: {{key: $event.data.schedule, window_s: {window}}}")
    out.append("  " + END)
    return "\n".join(out) + "\n"


def render_pins(lane: str) -> str:
    out = ["  " + BEGIN]
    for tid, *_ in TIMERS:
        doc = load_doc_text(render_pack(next(t for t in TIMERS if t[0] == tid), lane))
        out.append(f'  - {{pack: {pack_name(tid)}, digest: "{pack_digest(doc)}"}}')
    out.append("  " + END)
    return "\n".join(out) + "\n"


def load_doc_text(text: str):
    return yaml.load(text, Loader=UniqueKeyLoader)  # the budgeted, unique-key loader


_BLOCK = re.compile(r"[ ]*# cti-schedules:begin.*?# cti-schedules:end\n", re.S)


def _splice(path: Path, block: str, text: str) -> str:
    if _BLOCK.search(text):
        return _BLOCK.sub(lambda _m: block, text, count=1)
    if not text.endswith("\n"):
        text += "\n"
    return text + block


def binding_text() -> str:
    """The committed binding with the 23 rules added (before its built-in rule), for a site to render.

    The committed binding is not changed: rendering a rule adds files under the engine's own
    directory, and the product-name lint's baseline may not grow (docs/modules.md), so the site
    renders this binding (``hnx workflows st2 render --binding F --out DIR``) beside the repo's.
    """
    base = BINDING.read_text()
    block = render_rules()
    if "# A03:" not in base:
        raise ValueError("the binding has no built-in rule comment to insert the rules before")
    return base.replace("# A03:", block + "# A03:", 1)


def expected(lane: str) -> dict[Path, str]:
    """Every file this module owns (or a block of), as the table renders it for ``lane``."""
    files = {PACK_DIR / f"{pack_name(t[0])}.yml": render_pack(t, lane) for t in TIMERS}
    files[DEPLOY] = _splice(DEPLOY, render_pins(lane), DEPLOY.read_text())
    return files


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="cti_schedules", description=__doc__.splitlines()[0])
    ap.add_argument("--lane", choices=LANES, default=LANE)
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    mode.add_argument(
        "--binding-out", type=Path, metavar="FILE", help="write the binding with rules C01-C23"
    )
    args = ap.parse_args(argv)
    if args.binding_out:
        args.binding_out.write_text(binding_text())
        return 0
    drift = []
    for path, text in expected(args.lane).items():
        have = path.read_text() if path.exists() else None
        if have == text:
            continue
        if args.write:
            path.write_text(text)
        else:
            drift.append(str(path.relative_to(ROOT)))
    if drift:
        print("cti-schedules drift (run with --write):\n  " + "\n  ".join(drift), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
