"""The ``hnx_runtime`` label: which events come from a model runtime, decided by the pipeline.

The detections ``det:model-runtime-*`` match ``labels.hnx_runtime: model``.  A label an event
carries on arrival was written by whoever wrote the event, which for a model runtime's own logs is
the thing being watched, so the label is never taken from the event.  The pipeline sets it from a
table generated from the guest model (``hnx guests render --target runtime-labels``), joined on
the **observed source**: the address the collector itself saw (the peer of the connection a host
shipped its log over, or the client address a resolver or proxy recorded for a query it answered),
supplied beside the event and never read out of it.

:func:`enrich` is the rule, and every ``log-pipeline`` provider applies it (the contract,
``conformance/protocols/log_pipeline.py``):

* the observed address is in the table: the label is the table's value (``model`` or ``none``),
  whatever the event said;
* it is not, or there is none, or it does not parse: the event leaves without the label;
* every spelling the detection engine would read as the label is replaced, the nested
  ``labels.hnx_runtime`` and the flat ``"labels.hnx_runtime"`` key alike, and so is any spelling
  of either that differs only in case or surrounding white space (a back end that folds field
  names would read it); nothing else changes;
* a record that is not an object passes through unchanged: it has nowhere to carry the label.

The table is keyed by address only.  A host name in a log line is the sender's own claim, and a
name lookup at enrichment time would make the label as good as the resolver; an address the
collector saw is the one fact the runtime does not write.
"""

from __future__ import annotations

import copy
import ipaddress
import json
from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

#: the label key under ``labels``; ``FLAT_KEY`` is the same field as one dotted key
LABEL = "hnx_runtime"
FLAT_KEY = f"labels.{LABEL}"
SCHEMA = "homelabnext.logpipeline.runtime_labels/v1"
#: ``model``: serves models or runs model-written code; ``none``: a known guest that does neither
VALUES = ("model", "none")
GENERATED = "generated by hnx guests render; do not edit"
_TOP_KEYS = frozenset({"_generated", "schema", "label", "addresses"})
_ENTRY_KEYS = frozenset({"value", "guest", "capability"})


class TableError(ValueError):
    """A runtime table that is not a valid ``runtime_labels/v1`` document."""


def canonical_address(raw: Any) -> str | None:
    """The address as the table keys it, or None when ``raw`` is not a bare IP address.

    IPv6 is compressed and lower-case, and an IPv4-mapped IPv6 address (``::ffff:a.b.c.d``, what
    a dual-stack listener reports for an IPv4 peer) is its IPv4 address.  A port, a zone id, a
    network or a host name is not an address.
    """
    if not isinstance(raw, str) or raw != raw.strip() or "%" in raw:
        return None
    try:
        ip = ipaddress.ip_address(raw)
    except ValueError:
        return None
    if isinstance(ip, ipaddress.IPv6Address) and ip.ipv4_mapped is not None:
        ip = ip.ipv4_mapped
    return str(ip)


def _order(key: str) -> tuple[int, int]:
    ip = ipaddress.ip_address(key)
    return ip.version, int(ip)


def table_doc(rows: Iterable[tuple[str, str, str, str]]) -> dict[str, Any]:
    """A ``runtime_labels/v1`` document from ``(address, value, guest, capability)`` rows.

    Raises :class:`TableError` on an address that is not canonical, a value outside
    :data:`VALUES`, or one address given twice.
    """
    addresses: dict[str, dict[str, str]] = {}
    for address, value, guest, capability in rows:
        key = canonical_address(address)
        if key is None or key != address:
            raise TableError(f"{guest}: {address!r} is not a canonical IP address")
        if value not in VALUES:
            raise TableError(f"{guest}: value {value!r} is not one of {', '.join(VALUES)}")
        if key in addresses:
            raise TableError(f"{key}: claimed by {addresses[key]['guest']} and {guest}")
        addresses[key] = {"value": value, "guest": guest, "capability": capability}
    return {
        "_generated": GENERATED,
        "schema": SCHEMA,
        "label": LABEL,
        "addresses": dict(sorted(addresses.items(), key=lambda kv: _order(kv[0]))),
    }


@dataclass(frozen=True)
class RuntimeTable:
    """Observed address -> label value.  Build it with :meth:`from_doc` or :meth:`load`."""

    values: Mapping[str, str] = field(default_factory=dict)

    @classmethod
    def from_doc(cls, doc: Any) -> RuntimeTable:
        if not isinstance(doc, Mapping):
            raise TableError("a runtime table is a JSON object")
        extra = set(doc) - _TOP_KEYS
        if extra:
            raise TableError(f"unknown keys: {', '.join(sorted(map(str, extra)))}")
        if doc.get("schema") != SCHEMA:
            raise TableError(f"schema is {doc.get('schema')!r}, expected {SCHEMA!r}")
        if doc.get("label") != LABEL:
            raise TableError(f"label is {doc.get('label')!r}, expected {LABEL!r}")
        addresses = doc.get("addresses")
        if not isinstance(addresses, Mapping):
            raise TableError("addresses is not an object")
        values: dict[str, str] = {}
        for key, entry in addresses.items():
            if canonical_address(key) != key:
                raise TableError(f"{key!r} is not a canonical IP address")
            if not isinstance(entry, Mapping) or set(entry) - _ENTRY_KEYS:
                raise TableError(f"{key}: an entry holds value, guest and capability only")
            if entry.get("value") not in VALUES:
                raise TableError(f"{key}: value {entry.get('value')!r} is not one of {VALUES}")
            values[key] = entry["value"]
        return cls(values)

    @classmethod
    def load(cls, path: str | Path) -> RuntimeTable:
        try:
            doc = json.loads(Path(path).read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            raise TableError(f"{path}: {exc}") from None
        return cls.from_doc(doc)

    def lookup(self, observed: Any) -> str | None:
        key = canonical_address(observed)
        return None if key is None else self.values.get(key)


def _is(key: Any, name: str) -> bool:
    """``key`` spells ``name`` up to case and surrounding white space."""
    return isinstance(key, str) and str.casefold(str.strip(key)) == name


def drop_label(out: dict[str, Any], flat_key: str, label: str) -> None:
    """Remove, in place, every spelling of a pipeline-owned label from ``out``: the flat dotted
    ``flat_key`` and ``label`` under any ``labels`` object, up to case and surrounding white space
    (a back end that folds field names would read them as the label)."""
    for key in [k for k in out if _is(k, flat_key)]:
        del out[key]
    for holder in [v for k, v in out.items() if _is(k, "labels") and isinstance(v, dict)]:
        for key in [k for k in holder if _is(k, label)]:
            del holder[key]


def enrich(event: Any, observed: Any, table: RuntimeTable) -> Any:
    """A copy of ``event`` whose ``hnx_runtime`` label is the table's value for ``observed``.

    Any label the event arrived with is dropped first: the nested ``labels.hnx_runtime`` and the
    flat dotted key, and every spelling of either that differs only in case or surrounding white
    space (``Labels.HNX_RUNTIME``, ``"hnx_runtime "``), since a back end that folds field names
    would read those as the label.  An unknown or unparseable ``observed`` leaves the event
    without one.  ``labels`` that is not an object is replaced only when there is a label to set
    (it cannot carry one as it is).

    A record that is not an object (a JSON array, string or null) has no field to carry a label
    and none the engine reads, so it is returned unchanged (as a copy) rather than refused: one
    malformed record does not cost the rest of its batch.
    """
    if not isinstance(event, Mapping):
        return copy.deepcopy(event)
    out = copy.deepcopy(dict(event))
    drop_label(out, FLAT_KEY, LABEL)
    value = table.lookup(observed)
    if value is not None:
        if not isinstance(out.get("labels"), dict):
            out["labels"] = {}
        out["labels"][LABEL] = value
    return out
