"""The ``hnx_tlp`` label: each event's TLP label, from its source's declaration (ADR-0033).

An event's TLP label decides who may later read it, so, as with ``hnx_runtime``, a label an event
carries on arrival is never taken as the label: whoever wrote the event wrote it.  The pipeline
sets it from a table generated from the selected modules' datasets (``hnx modules render``:
``tlp-sources.json``), joined on the event's **route**: the dataset its collector input feeds,
named ``<module>/<dataset>`` and supplied beside the event by the collector, never read out of it.

:func:`enrich_tlp` is the rule, and every ``log-pipeline`` provider applies it (the contract,
``conformance/protocols/log_pipeline.py``):

* the route is in the table: the label is the dataset's declaration through
  :func:`homelabnext.tlp.item_label` (decision 3).  An item label the event carries (:func:`claims`:
  its ``tlp`` field, ``labels.tlp`` or the flat ``"labels.tlp"`` key; a ``tlp:`` tag in ``tags``;
  the ``tlp`` of an OCSF ``osint`` entry; a STIX TLP marking in ``object_marking_refs``; each key in
  any spelling that differs only in case or surrounding white space; several give the strictest) is
  kept when it is stricter, and when looser only if the dataset honours item labels; one that is
  not a label (``null`` included) is ``red``;
* the route is not in the table, there is none, or it is not a plain string: ``red``
  (decision 2).  Unlike the runtime label, an unknown source cannot stay unlabelled: a missing
  label must never read as a looser one;
* every spelling of the label the event arrived with is replaced, the nested ``labels.hnx_tlp``
  and the flat ``"labels.hnx_tlp"`` key alike, and any spelling of either that differs only in
  case or surrounding white space; nothing else changes (the event's own ``tlp`` field stays as
  it came: it is an input, and the lake's ``tlp`` column is ``labels.hnx_tlp``, never it);
* a record that is not an object passes through unchanged: it has nowhere to carry the label.
"""

from __future__ import annotations

import copy
import json
import re
from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from homelabnext import tlp

from .runtime_labels import _is, drop_label

#: the label key under ``labels``; ``FLAT_KEY`` is the same field as one dotted key
LABEL = "hnx_tlp"
FLAT_KEY = f"labels.{LABEL}"
#: the event field an item's own label arrives in (an input to the rule, never the result)
CLAIM = "tlp"
SCHEMA = "homelabnext.logpipeline.tlp_sources/v1"
GENERATED = "generated by hnx modules render; do not edit"
_TOP_KEYS = frozenset({"_generated", "schema", "label", "sources"})
_ENTRY_KEYS = frozenset({"tlp", "honour_item_labels", "module", "dataset"})
_PART = r"[a-z0-9][a-z0-9_-]{0,63}"
#: ``<module id>/<dataset id>``
ROUTE_RE = re.compile(rf"{_PART}/{_PART}")


class SourceTableError(ValueError):
    """A source table that is not a valid ``tlp_sources/v1`` document."""


def _route(raw: Any) -> str | None:
    """``raw`` as a table key, or None: an exact ``str`` matching ``<module>/<dataset>``."""
    if type(raw) is not str or ROUTE_RE.fullmatch(raw) is None:
        return None
    return raw


def table_doc(rows: Iterable[tuple[str, tlp.Label, bool]]) -> dict[str, Any]:
    """A ``tlp_sources/v1`` document from ``(route, declared label, honour_item_labels)`` rows.

    Raises :class:`SourceTableError` on a route that is not ``<module>/<dataset>``, a label that
    is not a :class:`~homelabnext.tlp.Label`, an honour flag that is not a bool, or a route given
    twice.
    """
    sources: dict[str, dict[str, Any]] = {}
    for route, label, honour in rows:
        if _route(route) is None:
            raise SourceTableError(f"{route!r} is not <module>/<dataset>")
        if type(label) is not tlp.Label:
            raise SourceTableError(f"{route}: label {label!r} is not a TLP label")
        if type(honour) is not bool:
            raise SourceTableError(f"{route}: honour_item_labels {honour!r} is not a bool")
        if route in sources:
            raise SourceTableError(f"{route}: given twice")
        module, dataset = route.split("/")
        sources[route] = {
            "tlp": str(label),
            "honour_item_labels": honour,
            "module": module,
            "dataset": dataset,
        }
    return {
        "_generated": GENERATED,
        "schema": SCHEMA,
        "label": LABEL,
        "sources": dict(sorted(sources.items())),
    }


@dataclass(frozen=True)
class SourceTable:
    """Route -> (declared label, honour_item_labels).  Build it with :meth:`from_doc` or
    :meth:`load`; an empty table labels every event ``red``."""

    sources: Mapping[str, tuple[tlp.Label, bool]] = field(default_factory=dict)

    @classmethod
    def from_doc(cls, doc: Any) -> SourceTable:
        if not isinstance(doc, Mapping):
            raise SourceTableError("a source table is a JSON object")
        extra = set(doc) - _TOP_KEYS
        if extra:
            raise SourceTableError(f"unknown keys: {', '.join(sorted(map(str, extra)))}")
        if doc.get("schema") != SCHEMA:
            raise SourceTableError(f"schema is {doc.get('schema')!r}, expected {SCHEMA!r}")
        if doc.get("label") != LABEL:
            raise SourceTableError(f"label is {doc.get('label')!r}, expected {LABEL!r}")
        sources = doc.get("sources")
        if not isinstance(sources, Mapping):
            raise SourceTableError("sources is not an object")
        out: dict[str, tuple[tlp.Label, bool]] = {}
        for key, entry in sources.items():
            route = _route(key)
            if route is None:
                raise SourceTableError(f"{key!r} is not <module>/<dataset>")
            if not isinstance(entry, Mapping) or set(entry) - _ENTRY_KEYS:
                raise SourceTableError(
                    f"{key}: an entry holds tlp, honour_item_labels, module and dataset only"
                )
            label = entry.get("tlp")
            if type(label) is not str or label not in tlp.LABELS:
                raise SourceTableError(f"{key}: tlp {label!r} is not a canonical TLP label")
            honour = entry.get("honour_item_labels")
            if type(honour) is not bool:
                raise SourceTableError(f"{key}: honour_item_labels {honour!r} is not a bool")
            if [entry.get("module"), entry.get("dataset")] != route.split("/"):
                raise SourceTableError(f"{key}: module and dataset do not spell the route")
            out[route] = (tlp.parse(label), honour)
        return cls(out)

    @classmethod
    def load(cls, path: str | Path) -> SourceTable:
        try:
            doc = json.loads(Path(path).read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            raise SourceTableError(f"{path}: {exc}") from None
        return cls.from_doc(doc)

    def lookup(self, route: Any) -> tuple[tlp.Label, bool] | None:
        key = _route(route)
        return None if key is None else self.sources.get(key)


#: the STIX 2.1 marking definitions of TLP: the TLP 2.0 ones (the TLP 2.0 marking extension) and
#: the TLP 1.0 ones the STIX 2.1 specification predefines (``white`` is ``clear``)
STIX_TLP_MARKINGS = {
    "marking-definition--94868c89-83c2-464b-929b-a1a8aa3c8487": "clear",
    "marking-definition--bab4a63c-aed9-4cf5-a766-dfca5abac2bb": "green",
    "marking-definition--55d920b0-5e8b-4f79-9ee9-91f868d9b421": "amber",
    "marking-definition--939a9414-2ddd-4d32-a0cd-375ea402b003": "amber+strict",
    "marking-definition--e828b379-4e03-4974-9ac4-e53a884c97c1": "red",
    "marking-definition--613f2e26-407d-48c7-9eca-b8e91df99dc9": "clear",
    "marking-definition--34098fce-860f-48ae-8e50-ebd3cc5e41da": "green",
    "marking-definition--f88d31f6-486f-44da-b317-01333bde0b82": "amber",
    "marking-definition--5e57c739-391a-4eb3-b6be-7d15ca92d5ed": "red",
}


def _items(value: Any) -> list[Any]:
    """``value`` as a list: a list as itself, anything else as its one item."""
    return list(value) if isinstance(value, list) else [value]


def _tag_claim(tag: Any) -> Any:
    """The label a tag carries, or ``None`` for a tag that is not a TLP one.  A tag is a string
    or an object with a ``name`` (a MISP tag); a TLP tag starts ``tlp:`` and is read whole, so
    ``tlp:amber-strict`` or ``tlp:unknown`` is a claim that is not a label (``red``)."""
    if isinstance(tag, Mapping):
        tag = next((v for k, v in tag.items() if _is(k, "name")), None)
    if isinstance(tag, str) and str.casefold(str.strip(tag)).startswith("tlp:"):
        return tag
    return None


def claims(event: Mapping[str, Any]) -> list[Any]:
    """The item labels ``event`` carries, each key in any spelling up to case and surrounding
    white space:

    * its ``tlp`` field, the flat ``"labels.tlp"`` key and ``labels.tlp``;
    * every ``tlp:`` tag in ``tags`` (a string or a MISP tag object; other tags are not labels);
    * the ``tlp`` of each OCSF ``osint`` entry that has one (the label a source gave the
      indicator);
    * each STIX TLP marking in ``object_marking_refs`` (:data:`STIX_TLP_MARKINGS`; a marking that
      is not a TLP one, a statement say, is not a label).
    """
    out = [v for k, v in event.items() if _is(k, CLAIM) or _is(k, f"labels.{CLAIM}")]
    for holder in [v for k, v in event.items() if _is(k, "labels") and isinstance(v, Mapping)]:
        out += [v for k, v in holder.items() if _is(k, CLAIM)]
    for tags in [v for k, v in event.items() if _is(k, "tags")]:
        out += [c for c in map(_tag_claim, _items(tags)) if c is not None]
    for osint in [v for k, v in event.items() if _is(k, "osint")]:
        for entry in _items(osint):
            if isinstance(entry, Mapping):
                out += [v for k, v in entry.items() if _is(k, CLAIM)]
    for refs in [v for k, v in event.items() if _is(k, "object_marking_refs")]:
        for ref in _items(refs):
            if isinstance(ref, str) and str.casefold(str.strip(ref)) in STIX_TLP_MARKINGS:
                out.append(STIX_TLP_MARKINGS[str.casefold(str.strip(ref))])
    return out


def label_for(event: Mapping[str, Any], route: Any, table: SourceTable) -> tlp.Label:
    """The TLP label of one object event that arrived on ``route`` (see the module doc)."""
    entry = table.lookup(route)
    if entry is None:
        return tlp.Label.RED
    declared, honour = entry
    carried = claims(event)
    if not carried:
        return tlp.item_label(declared, honour_item_labels=honour)
    return max(tlp.item_label(declared, c, honour_item_labels=honour) for c in carried)


def enrich_tlp(event: Any, route: Any, table: SourceTable) -> Any:
    """A copy of ``event`` whose ``labels.hnx_tlp`` is its label from ``route``'s declaration.

    Any ``hnx_tlp`` label the event arrived with is dropped first, nested or flat, in any
    spelling that differs only in case or surrounding white space.  ``labels`` that is not an
    object is replaced (it cannot carry the label as it is).  A record that is not an object is
    returned unchanged (as a copy).
    """
    if not isinstance(event, Mapping):
        return copy.deepcopy(event)
    label = label_for(event, route, table)
    out = copy.deepcopy(dict(event))
    drop_label(out, FLAT_KEY, LABEL)
    if not isinstance(out.get("labels"), dict):
        out["labels"] = {}
    out["labels"][LABEL] = str(label)
    return out
