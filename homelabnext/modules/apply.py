"""The module apply path (ADR-0027, proposed; docs/modules/apply.md): from a checked site
selection, what Ansible needs to install the placed modules.

Two renders share one naming rule, :func:`module_group`, so they agree by construction:

* the **inventory groups** ``mod_<module id>_<host role>`` (``-`` as ``_``), one per placed host
  role, each listing the guest every placement of that role lands on
  (:func:`inventory_groups`; ``hnx guests render --target inventory --selection FILE`` adds them
  to the guest inventory);
* the **playbooks** (:func:`render`; ``hnx modules render`` writes them): ``modules.yml``, one
  play per placed host role of each selected module, in the order of the modules' hard
  requirements, each play on that role's group alone and running the roles the module lists for
  the host role (``requires.hosts[].roles``; role interface v1 ``main``), after the role's own
  preflight hooks (``contributes.preflight``); and ``checks/<module>.yml`` per placed module,
  which runs every one of its roles' ``readiness`` and then ``health`` hook on each of its groups.

A play's ``hosts`` is always one ``mod_*`` group the site's placement fills, never a group a
module names: a module cannot reach a host the site did not place it on (``role_lint`` PB001
holds by construction).  The module's own ``lifecycle.install`` playbook is not imported here:
its plays name their own hosts, which is the site's to decide.

Everything here is a pure function of the selection and the manifests (ADR-0028): the role paths
are passed in, relative to the directory the playbooks are written to.
"""

from __future__ import annotations

import heapq
import json
import re
from collections.abc import Callable, Mapping
from dataclasses import dataclass
from typing import Any

from homelabnext.modules.rules import us

Doc = dict[str, Any]

#: the group prefix every module group carries (no guest-model group starts with it)
GROUP_PREFIX = "mod_"
#: the install playbook ``hnx modules render`` writes, and the directory of the check playbooks
PLAYBOOK = "modules.yml"
CHECKS_DIR = "checks"
#: the role interface v1 hooks a check playbook runs, in this order (docs/role-interface.md)
CHECK_HOOKS = ("readiness", "health")
HEADER = "generated by hnx modules render; do not edit"


class ApplyError(Exception):
    """The selection cannot be turned into an apply (a cycle, a name clash, an unknown host)."""


@dataclass(frozen=True, order=True)
class Placement:
    """One host role of one selected module on one site host (``instance`` is the slot instance
    of a provider's placement, None for a feature's or a core module's)."""

    module: str
    role: str
    host: str
    instance: str | None = None


def module_group(module: str, role: str) -> str:
    """The inventory group of a module's host role: ``mod_<module id>_<host role>``, ``-`` as
    ``_`` (``web-app`` / ``server`` -> ``mod_web_app_server``)."""
    return f"{GROUP_PREFIX}{us(module)}_{us(role)}"


def placements(site: Mapping[str, Any]) -> list[Placement]:
    """Every placement of a (schema-valid) selection: a provider's per slot instance, a
    feature's and a core module's.  Sorted; an instance that fills several slots with one
    placement is listed once."""
    rows: set[Placement] = set()
    for chosen in (site.get("slots") or {}).values():
        for c in chosen if isinstance(chosen, list) else []:
            for role, host in (c.get("placement") or {}).items():
                rows.add(Placement(c["provider"], role, host, c.get("instance")))
    for section in ("features", "core"):
        for name, entry in (site.get(section) or {}).items():
            for role, host in ((entry or {}).get("placement") or {}).items():
                rows.add(Placement(name, role, host))
    return sorted(rows, key=lambda p: (p.module, p.role, p.host, p.instance or ""))


def _group_clashes(pairs: set[tuple[str, str]]) -> list[str]:
    """Two (module, host role) pairs whose group names are equal (``a-b``/``c`` and ``a``/``b-c``
    are both ``mod_a_b_c``): one group would run both modules' roles."""
    by_group: dict[str, set[tuple[str, str]]] = {}
    for mod, role in pairs:
        by_group.setdefault(module_group(mod, role), set()).add((mod, role))
    return [
        f"{g}: the group of " + " and of ".join(f"{m}/{r}" for m, r in sorted(names))
        for g, names in sorted(by_group.items())
        if len(names) > 1
    ]


def inventory_groups(
    site: Mapping[str, Any],
    host_of: Callable[[str], str | None],
    taken: frozenset[str] = frozenset(),
) -> dict[str, list[str]]:
    """``mod_*`` group -> the sorted inventory hosts it holds.  Each placement's site host must
    reference a guest (``hosts.<name>.guest``) that ``host_of`` (guest id -> inventory host name,
    None for no such guest) knows: a stand-in host is no machine Ansible can reach.  A placement
    on an ``external`` stand-in host runs outside the lab and gets no group.  ``taken`` are the
    inventory's other group names, which a module group may not equal.  Raises
    :class:`ApplyError` naming every problem."""
    hosts = site.get("hosts") or {}
    groups: dict[str, set[str]] = {}
    problems: list[str] = []
    rows = placements(site)
    for p in rows:
        who = f"{p.module}/{p.role}" + (f" ({p.instance})" if p.instance else "")
        h = hosts.get(p.host)
        if not isinstance(h, Mapping):
            problems.append(f"{who}: placed on {p.host}, which hosts does not define")
            continue
        gid = h.get("guest")
        if gid is None:
            if h.get("kind") == "external":
                continue  # outside the lab: no inventory host
            problems.append(
                f"{who}: placed on {p.host}, a stand-in host (kind and capacity, no guest); the "
                f"inventory needs hosts.{p.host}.guest naming the guest it runs on"
            )
            continue
        name = host_of(gid)
        if name is None:
            problems.append(f"{who}: hosts.{p.host} references {gid}, which is no guest here")
            continue
        groups.setdefault(module_group(p.module, p.role), set()).add(name)
    problems += _group_clashes({(p.module, p.role) for p in rows})
    problems += [
        f"{g}: a module group with the name of a guest-model group"
        for g in sorted(groups)
        if g in taken
    ]
    if problems:
        raise ApplyError("; ".join(problems))
    return {g: sorted(v) for g, v in sorted(groups.items())}


# ----------------------------------------------------------------------------- install order


def _providers_of(site: Mapping[str, Any], slot: str, instance: str | None) -> set[str]:
    chosen = (site.get("slots") or {}).get(slot)
    if not isinstance(chosen, list):
        return set()  # none, pass-through, an incumbent or unselected: nothing to install first
    return {c["provider"] for c in chosen if instance is None or c.get("instance") == instance}


def install_order(site: Mapping[str, Any], sel: Mapping[str, Doc]) -> list[str]:
    """The selected modules, each after every module that serves a slot it hard-requires
    (``requires.capabilities``: the provider of that slot instance, or of every instance when
    the requirement names none).  Soft requirements (``prefers``) and incumbents order nothing.
    Ties go by id, so the order is a function of the inputs.  Raises :class:`ApplyError` on a
    cycle, naming the modules in it."""
    after: dict[str, set[str]] = {m: set() for m in sel}
    for m, doc in sel.items():
        for req in (doc.get("requires") or {}).get("capabilities", []):
            slot = str(req.get("cap", "")).removeprefix("cap:")
            for p in _providers_of(site, slot, req.get("instance")):
                if p != m and p in sel:
                    after[m].add(p)
    waiting = {m: len(deps) for m, deps in after.items()}
    unblocks: dict[str, list[str]] = {m: [] for m in sel}
    for m, deps in after.items():
        for d in deps:
            unblocks[d].append(m)
    ready = [m for m, n in waiting.items() if n == 0]
    heapq.heapify(ready)
    order: list[str] = []
    while ready:
        m = heapq.heappop(ready)
        order.append(m)
        for n in unblocks[m]:
            waiting[n] -= 1
            if waiting[n] == 0:
                heapq.heappush(ready, n)
    if len(order) != len(sel):
        # what is left is the cycles and what waits on them: peel off every module nothing
        # left waits for (downstream of a cycle, not in one), so the error names the cycle
        left = {m for m, n in waiting.items() if n > 0}
        while True:
            tail = {m for m in left if not any(m in after[o] for o in left)}
            if not tail:
                break
            left -= tail
        cycle = sorted(left)
        raise ApplyError(
            "the modules' hard requirements form a cycle, so no install order exists: "
            + ", ".join(cycle)
        )
    return order


# ----------------------------------------------------------------------------- playbooks


#: what a name written into a playbook unquoted may be (a group, a tag, a comment): the schema's
#: id and host-role shape; render() refuses anything else even when called without the schema
_NAME = re.compile(r"[a-z][a-z0-9]*(?:-[a-z0-9]+)*\Z")
#: a version or kind shown in a comment
_WORD = re.compile(r"[A-Za-z0-9][A-Za-z0-9.+_-]{0,63}\Z")
#: one segment of a role path (``..`` for the way up from the render directory); never ``{``,
#: ``%`` or ``#``, which Ansible templates in a role name
_SEGMENT = re.compile(r"(?:\.\.|[A-Za-z0-9_][A-Za-z0-9._-]*)\Z")
#: what an inventory group of a module looks like
_GROUP = re.compile(r"mod_[a-z0-9_]+\Z")


def _safe_path(path: str) -> str:
    segs = path.split("/")
    if path.startswith("/"):
        segs = segs[1:]
    if not segs or not all(_SEGMENT.match(x) for x in segs):
        raise ApplyError(f"role path {path!r}: not a plain relative or absolute path")
    return path


def _names_problems(
    placed: Mapping[str, list[tuple[str, Doc]]], sel: Mapping[str, Doc]
) -> list[str]:
    """Every value written into a playbook outside a JSON-quoted string, held to its shape."""
    out = []
    for mod in sel:
        doc = sel[mod]
        if not _NAME.match(str(mod)):
            out.append(f"module id {mod!r}: not a module id")
        for key in ("kind", "version"):
            if key in doc and not _WORD.match(str(doc[key])):
                out.append(f"{mod}: {key} {doc[key]!r} is not a plain word")
    for mod, rows in placed.items():
        for role, _h in rows:
            if not _NAME.match(str(role)):
                out.append(f"{mod}: host role {role!r} is not a host role name")
            if not _GROUP.match(module_group(str(mod), str(role))):
                out.append(f"{mod}/{role}: no module group can be named from it")
        for e in sel[mod].get("contributes", {}).get("preflight", []):
            if e.get("hook") not in CHECK_HOOKS:
                out.append(f"{mod}: preflight hook {e.get('hook')!r} is not readiness or health")
    return out


def _guard(groups: list[str]) -> list[str]:
    """The first play: every module group the playbook targets holds a host.  Without it a play
    on a group the inventory lacks (rendered without ``--selection``, or from another selection)
    is "skipping: no hosts matched", and ``ansible-playbook`` exits 0: a silent install or a
    green check that ran nothing.  Tagged ``always``, so ``--tags`` keeps it."""
    return [
        '- name: "every module group is in the inventory"',
        "  hosts: localhost",
        "  gather_facts: false",
        "  tags: [always]",
        "  tasks:",
        '    - name: "refuse an inventory without the module groups"',
        "      ansible.builtin.assert:",
        '        that: "(groups[item] | default([])) | length > 0"',
        '        fail_msg: "{{ item }} holds no host: render the inventory with '
        "hnx guests render --target inventory --selection (the selection this playbook was "
        'rendered from)"',
        "        quiet: true",
        f"      loop: [{', '.join(groups)}]",
    ]


def _q(value: Any) -> str:
    """A JSON-quoted scalar (valid YAML; no value adds YAML of its own)."""
    return json.dumps(value, ensure_ascii=True)


def _host_role(doc: Doc, role: str) -> Doc | None:
    return next((h for h in doc["requires"].get("hosts", []) if h["role"] == role), None)


def _role_files(doc: Doc) -> dict[str, str]:
    """``role:<name>`` -> the role directory inside the module (``contributes.roles``)."""
    return {
        "role:" + e["file"].rstrip("/").rsplit("/", 1)[-1]: e["file"].rstrip("/")
        for e in doc.get("contributes", {}).get("roles", [])
    }


def _role_path(module_dirs: Mapping[str, str], mod: str, doc: Doc, ref: str) -> str:
    files = _role_files(doc)
    if ref not in files:
        raise ApplyError(f"{mod}: {ref} is not a role the module contributes")
    return _safe_path(f"{module_dirs[mod].rstrip('/')}/{files[ref]}")


def _include(path: str, hook: str, name: str) -> list[str]:
    """A task that runs one hook of a role, tagged so ``--tags <hook>`` selects it and every
    task it includes (``apply``)."""
    return [
        f"    - name: {_q(name)}",
        "      ansible.builtin.include_role:",
        f"        name: {_q(path)}",
        f"        tasks_from: {hook}",
        f"        apply: {{tags: [{hook}]}}",
        f"      tags: [{hook}]",
    ]


def _plays(site: Mapping[str, Any], sel: Mapping[str, Doc]) -> dict[str, list[tuple[str, Doc]]]:
    """Module -> its placed host roles (each with its manifest entry), sorted by role; a role the
    module does not declare is refused (``hnx modules check`` reports it first)."""
    out: dict[str, list[tuple[str, Doc]]] = {}
    for mod, role in sorted({(p.module, p.role) for p in placements(site)}):
        if mod not in sel:
            raise ApplyError(f"{mod}: placed, but no manifest of it was selected")
        h = _host_role(sel[mod], role)
        if h is None:
            raise ApplyError(f"{mod}: placement names {role}, not one of its host roles")
        out.setdefault(mod, []).append((role, h))
    return out


def render(
    site: Mapping[str, Any], sel: Mapping[str, Doc], module_dirs: Mapping[str, str]
) -> dict[str, str]:
    """``modules.yml`` and ``checks/<module>.yml`` for every placed module.  ``site`` is the
    checked selection, ``sel`` the selected manifests (:func:`homelabnext.modules.rules.selected`)
    and ``module_dirs`` each module's directory as the playbooks will reach it (relative to the
    directory they are written to).  Raises :class:`ApplyError`."""
    placed = _plays(site, sel)
    bad = _names_problems(placed, sel)
    if bad:
        raise ApplyError("; ".join(bad))
    clashes = _group_clashes({(m, r) for m, rows in placed.items() for r, _h in rows})
    if clashes:
        raise ApplyError("; ".join(clashes))
    order = install_order(site, sel)
    L = [
        f"# {HEADER}",
        "# Installs each placed module on the inventory group of each of its host roles",
        "# (mod_<module>_<host role>, hnx guests render --target inventory --selection), in the",
        "# order of the modules' hard requirements. One module: --tags mod_<module>.",
        f"# install order: {', '.join(order) if order else '(no module selected)'}",
    ]
    files: dict[str, str] = {}
    targets: list[str] = []
    plays = 0
    for mod in order:
        rows = placed.get(mod)
        if not rows:
            L += ["", f"# module {mod}: placed on no host (hosted, config-only or unplaced)"]
            continue
        doc = sel[mod]
        L += ["", f"# ---- module {mod} ({doc['kind']}, {doc.get('version', '?')})"]
        check: list[str] = []
        mine: list[str] = []
        for role, h in rows:
            group = module_group(mod, role)
            name = f"module {mod}: host role {role}"
            if h["kind"] == "external":
                L.append(f"# {name}: an external role runs outside the lab; nothing to apply")
                continue
            refs = list(h.get("roles", []))
            if not refs:
                L.append(f"# {name}: lists no roles (requires.hosts[].roles); nothing to apply")
                continue
            paths = [_role_path(module_dirs, mod, doc, r) for r in refs]
            pre = [
                (p, e["hook"])
                for e in doc.get("contributes", {}).get("preflight", [])
                for r, p in zip(refs, paths, strict=True)
                if e["role"] == r
            ]
            plays += 1
            targets.append(group)
            mine.append(group)
            L += [
                f"- name: {_q(name)}",
                f"  hosts: {group}",
                # a module's roles install packages, units and files: the play escalates
                "  become: true",
                # the module's tag only: a group tag could equal another module's tag
                # (module a-b is mod_a_b; module a's host role b is mod_a_b too)
                f"  tags: [{GROUP_PREFIX}{us(mod)}]",
            ]
            if pre:
                L.append("  pre_tasks:")
                for path, hook in pre:
                    L += _include(path, hook, f"preflight {hook}: {path.rsplit('/', 1)[-1]}")
            L.append("  roles:")
            L += [f"    - role: {_q(p)}" for p in paths]
            check += [
                "",
                f"- name: {_q(f'{name}: readiness, health')}",
                f"  hosts: {group}",
                "  become: true",
                "  gather_facts: false",
                "  tasks:",
            ]
            for hook in CHECK_HOOKS:
                for p in paths:
                    # a check playbook is one directory down (checks/): a role path relative
                    # to the render directory is one more level up from it
                    there = p if p.startswith("/") else f"../{p}"
                    check += _include(there, hook, f"{hook}: {p.rsplit('/', 1)[-1]}")
        if mine:
            head = [
                f"# {HEADER}",
                f"# The readiness and then the health hook of every role of module {mod}, on each",
                "# group it is placed on. Read-only by the role interface v1 contract.",
                "",
                *_guard(mine),
            ]
            files[f"{CHECKS_DIR}/{mod}.yml"] = "\n".join(head + check) + "\n"
    if not plays:
        L += [
            "",
            "# no placed module has a role to apply",
            "- name: no module to apply",
            "  hosts: localhost",
            "  gather_facts: false",
        ]
    else:
        L[5:5] = ["", *_guard(targets)]
    files[PLAYBOOK] = "\n".join(L) + "\n"
    return files
